// -----------------------------------------------------------------------
// Generates "Import Route" -- the device half of the route install.
// -----------------------------------------------------------------------
//   node ./scripts/generate-import-route
//
// Lives in the offline file. Replaces the local route with the server's:
//
//   1. Refuses while any edit is waiting to upload (as Initial Download does).
//   2. Calls "Build Route Export" over the OData script endpoint with
//      { account } -- Get ( AccountName ) unless a parameter names one.
//   3. Downloads every table first: RouteExports(<key>)/File/$value is base64
//      text; Base64Decode rebuilds the Merge file in Sync_Settings::zg_RouteFile
//      and Export Field Contents writes it to the temp folder. Nothing local
//      is touched until every table is on the device.
//   4. Per table: Show All, Delete All, Import Records by field name, auto-
//      enter off (so __ID, server keys and zzModifiedTimestamp arrive as they
//      are). Locations and equipment then get z_serverModTimestamp from
//      zzModifiedTimestamp -- UploadChanges' conflict check needs it -- and
//      equipment gets z_lastDownload, which Initial Download's purge reads.
//   5. Sync_Settings as Initial Download's FINISH: LastSyncUTC, Initialized,
//      DatabaseUUID (the environment guard) and CustomersJSON.
//   6. Deletes the server's RouteExports records, success or not.
//
// Returns JSON -- { success, account, tables: { LABEL: { expected, imported,
// importError } }, ms... } or { error } -- and shows nothing: First Setup and
// the widget decide what to tell the tech.
//
// Every mechanism here was proven on FileMaker Go by the zProbe scripts; the
// largest route under the probe's cap (13,750 equipment rows) took ~26 s.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");
const MAP = require("./routeTables.json");

const SCRIPT = "Import Route";
const HOST = "https://gr.cranstonhost.com/fmi/odata/v4/";
const SERVER_SCRIPT = "Build Route Export";
const ROUTE_FIELD = { table: "Sync_Settings", id: 36, name: "zg_RouteFile" };
const SETTINGS_LAYOUT = { id: 4, name: "Sync_Settings" };
const NOW = "Get ( CurrentTimeUTCMilliseconds )";
const STATUS_CALC = `Let ( p = Position ( $headerResponse ; "HTTP/" ; Length ( $headerResponse ) ; -1 ) ; GetAsNumber ( Middle ( $headerResponse ; Position ( $headerResponse ; " " ; p ; 1 ) + 1 ; 3 ) ) )`;
// Offline field ids (DDR 2026-10-15) for the stamps written after import.
const STAMPS = {
  LOCATIONS: { serverMod: 175 },
  EQUIPMENT: { serverMod: 79, lastDownload: 86 },
};
const x = (label) => label.replace(/\W+/g, "_");

const curl = (method, withBody) =>
  [
    `"--X ${method}`,
    '--H \\"Accept: application/json\\"',
    '--H \\"OData-Version: 4.0\\"',
    ...(withBody ? ['--H \\"Content-Type: application/json\\"'] : []),
    '--H \\"Authorization: Basic " & $auth & "\\"',
    ...(withBody ? ["--data @$body"] : []),
    "--dump-header $headerResponse",
    '"',
  ].join("\n");

const fail = (messageCalc) => [
  S.setVar("$result", `JSONSetElement ( "{}" ; [ "error" ; ${messageCalc} ; JSONString ] )`),
  S.exitScript("$result"),
];

function build() {
  const steps = [
    S.comment("Description: Replaces this device's route with a fresh copy prepared on the"),
    S.comment("server by Build Route Export. Returns JSON; shows nothing."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-import-route.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("PARAMS AND GUARDS"),
    S.setErrorCapture(true),
    S.comment("Freeze: the table layouts below are working context, not something to show."),
    S.freezeWindow(),
    S.allowUserAbort(false),
    S.setVar("$t0", NOW),
    S.setVar("$runStamp", "Get ( CurrentTimestamp )"),
    S.setVar(
      "$account",
      `Let ( a = JSONGetElement ( Get ( ScriptParameter ) ; "account" ) ; If ( IsEmpty ( a ) or Left ( a ; 1 ) = "?" ; Get ( AccountName ) ; a ) )`
    ),
    S.comment("_ODataAuth returns \"?\" when the account cannot view Credential (fixed in"),
    S.comment("fmscripts/calcs/_ODataAuth.txt); treat that as missing too."),
    S.setVar("$auth", "_ODataAuth ( )"),
    S.ifStep(`IsEmpty ( $auth ) or Left ( $auth ; 1 ) = "?"`),
    ...fail(`"This copy has no server credentials, or this account cannot read them. Nothing was downloaded."`),
    S.endIf(),
    S.setVar(
      "$pending",
      `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"CUSTOMER_EQUIPMENT\\" where \\"f_pendingSync\\" = 1" ; "" ; "" ) ) ) + Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"Locations\\" where \\"f_pendingSync\\" = 1" ; "" ; "" ) ) )`
    ),
    S.ifStep("$pending > 0"),
    ...fail(`$pending & " change(s) haven't been uploaded yet. Upload them first, then download your route."`),
    S.endIf(),
    S.setVar("$database", `Case ( inSandbox ; "GSR_Gaskets Rock_Sandbox" ; "GSR_Gaskets Rock" )`),
    S.setVar("$base", `${JSON.stringify(HOST)} & $database & "/"`),
    S.comment(""),
    S.banner("1. ASK THE SERVER TO PREPARE THE ROUTE"),
    S.setVar("$url", `$base & "Script.${SERVER_SCRIPT}"`),
    S.setVar(
      "$body",
      `JSONSetElement ( "{}" ; "scriptParameterValue" ; JSONSetElement ( "{}" ; "account" ; $account ; JSONString ) ; JSONString )`
    ),
    S.setVar("$curl", curl("POST", true)),
    S.setVar("$headerResponse", `""`),
    S.insertFromURL("$url", "$curl", "$response"),
    S.setVar("$netError", "Get ( LastError )"),
    S.setVar("$status", STATUS_CALC),
    S.setVar("$callMs", `${NOW} - $t0`),
    S.setVar("$server", `JSONGetElement ( $response ; "scriptResult.resultParameter" )`),
    S.ifStep("$netError ≠ 0"),
    ...fail(`"Could not reach the server (error " & $netError & "). Check the connection and try again."`),
    S.endIf(),
    S.ifStep("$status < 200 or $status > 299"),
    ...fail(`"The server refused the request (" & $status & Let ( m = JSONGetElement ( $response ; "error.message" ) ; If ( IsEmpty ( m ) or Left ( m ; 1 ) = "?" ; "" ; ": " & m ) ) & ")."`),
    S.endIf(),
    S.setVar("$serverError", `JSONGetElement ( $server ; "error" )`),
    S.ifStep(`not IsEmpty ( $serverError ) and Left ( $serverError ; 1 ) ≠ "?"`),
    ...fail("$serverError"),
    S.endIf(),
    S.ifStep(`IsEmpty ( $server ) or Left ( JSONGetElement ( $server ; "tables" ) ; 1 ) = "?"`),
    ...fail(`"The server's reply was not understood. Nothing was downloaded."`),
    S.endIf(),
    S.setVar("$customers", `JSONGetElement ( $server ; "customers" )`),
    S.setVar("$keys", `""`),
    S.comment(""),
    S.banner("2. DOWNLOAD EVERY TABLE BEFORE TOUCHING LOCAL DATA"),
    S.setVar("$getCurl", curl("GET", false)),
    S.setVar("$err", `""`),
    S.setVar("$t1", NOW),
    ...MAP.tables.flatMap((t) => {
      const k = x(t.label);
      return [
        S.setVar(`$key_${k}`, `Let ( v = JSONGetElement ( $server ; "tables.${k}.key" ) ; If ( Left ( v ; 1 ) = "?" ; "" ; v ) )`),
        S.setVar(`$expected_${k}`, `GetAsNumber ( JSONGetElement ( $server ; "tables.${k}.rows" ) )`),
        S.setVar(`$path_${k}`, `""`),
        S.ifStep(`IsEmpty ( $err ) and not IsEmpty ( $key_${k} )`),
        S.setVar("$keys", `List ( $keys ; $key_${k} )`),
        S.setVar("$fileUrl", `$base & "RouteExports(" & $key_${k} & ")/File/$value"`),
        S.setVar("$headerResponse", `""`),
        S.insertFromURL("$fileUrl", "$getCurl", "$data"),
        S.setVar("$dlError", "Get ( LastError )"),
        S.setVar("$dlStatus", STATUS_CALC),
        S.ifStep(`$dlError ≠ 0 or $dlStatus ≠ 200 or Length ( $data ) = 0`),
        S.setVar("$err", `"Download of ${t.label.toLowerCase()} failed (" & If ( $dlError ≠ 0 ; "error " & $dlError ; "status " & $dlStatus ) & ")."`),
        S.elseStep(),
        S.setFieldByName(`"${ROUTE_FIELD.table}::${ROUTE_FIELD.name}"`, `Base64Decode ( $data ; "route_${k.toLowerCase()}.mer" )`),
        S.setVar(`$path_${k}`, `Get ( TemporaryPath ) & "route_${k.toLowerCase()}.mer"`),
        S.exportFieldContents(ROUTE_FIELD, `$path_${k}`),
        S.ifStep("Get ( LastError ) ≠ 0"),
        S.setVar("$err", `"Could not unpack ${t.label.toLowerCase()} on this device (error " & Get ( LastError ) & ")."`),
        S.endIf(),
        S.endIf(),
        S.setVar("$data", `""`),
        S.endIf(),
      ];
    }),
    S.setFieldByName(`"${ROUTE_FIELD.table}::${ROUTE_FIELD.name}"`, `""`),
    S.setVar("$downloadMs", `${NOW} - $t1`),
    S.comment(""),
    S.banner("3. REPLACE EACH TABLE"),
    S.comment("Every file is on the device by now; a failed download stops before this."),
    S.setVar("$tables", `"{}"`),
    S.setVar("$warnings", `""`),
    S.setVar("$t2", NOW),
    S.ifStep("IsEmpty ( $err )"),
    ...MAP.tables.flatMap((t) => {
      const k = x(t.label);
      const st = STAMPS[t.label];
      const to = t.offline.to.name;
      return [
        S.comment(`-- ${t.label}`),
        S.goToLayout(t.offline.layout.id, t.offline.layout.name),
        S.showAllRecords(),
        S.ifStep("Get ( FoundCount ) > 0"),
        S.deleteAllRecords(),
        S.endIf(),
        S.setVar(`$imported_${k}`, "0"),
        S.setVar(`$importError_${k}`, `""`),
        S.ifStep(`not IsEmpty ( $path_${k} )`),
        S.importRecordsMerge(`$path_${k}`, t.offline.to, t.fields.map((f) => ({ id: f.offline, name: f.name })), "Add"),
        S.setVar(`$importError_${k}`, "Get ( LastError )"),
        S.setVar(`$imported_${k}`, "Get ( FoundCount )"),
        ...(st
          ? [
              S.ifStep(`$importError_${k} = 0 and $imported_${k} > 0`),
              S.replaceFieldContents({ table: to, id: st.serverMod, name: "z_serverModTimestamp" }, `${to}::zzModifiedTimestamp`),
              ...(st.lastDownload
                ? [S.replaceFieldContents({ table: to, id: st.lastDownload, name: "z_lastDownload" }, "$runStamp")]
                : []),
              S.endIf(),
            ]
          : []),
        S.endIf(),
        S.ifStep(`$imported_${k} ≠ $expected_${k} or ( not IsEmpty ( $importError_${k} ) and $importError_${k} ≠ 0 )`),
        S.setVar("$warnings", `List ( $warnings ; "${t.label.toLowerCase()}: expected " & $expected_${k} & ", imported " & $imported_${k} & If ( not IsEmpty ( $importError_${k} ) and $importError_${k} ≠ 0 ; " (error " & $importError_${k} & ")" ; "" ) )`),
        S.endIf(),
        S.setVar(
          "$tables",
          `JSONSetElement ( $tables ; "${k}" ; JSONSetElement ( "{}" ; [ "expected" ; $expected_${k} ; JSONNumber ] ; [ "imported" ; $imported_${k} ; JSONNumber ] ; [ "importError" ; $importError_${k} ; JSONString ] ) ; JSONObject )`
        ),
      ];
    }),
    S.comment(""),
    S.banner("4. SYNC SETTINGS, AS INITIAL DOWNLOAD'S FINISH"),
    S.goToLayout(SETTINGS_LAYOUT.id, SETTINGS_LAYOUT.name),
    S.ifStep("Get ( FoundCount ) = 0"),
    S.newRecord(),
    S.endIf(),
    S.setFieldByName(`"Sync_Settings::LastSyncUTC"`, "Get ( CurrentTimeUTCMilliseconds )"),
    S.setFieldByName(`"Sync_Settings::Initialized"`, `"1"`),
    S.comment("Which database the data came from: UploadChanges refuses to post anywhere else."),
    S.setFieldByName(`"Sync_Settings::DatabaseUUID"`, "$database"),
    S.setFieldByName(`"Sync_Settings::CustomersJSON"`, "$customers"),
    S.commit(),
    S.setVar("$$LAST_DOWNLOAD", "Get ( CurrentTimestamp )"),
    S.endIf(),
    S.setVar("$importMs", `${NOW} - $t2`),
    S.comment(""),
    S.banner("5. DELETE THE SERVER'S COPIES, SUCCESS OR NOT"),
    S.setVar("$delCurl", curl("DELETE", false)),
    S.setVar("$d", "0"),
    S.loop(),
    S.setVar("$d", "$d + 1"),
    S.setVar("$delKey", "GetValue ( $keys ; $d )"),
    S.exitLoopIf("IsEmpty ( $delKey )"),
    S.setVar("$headerResponse", `""`),
    S.setVar("$delUrl", `$base & "RouteExports(" & $delKey & ")"`),
    S.insertFromURL("$delUrl", "$delCurl", "$delResponse"),
    S.endLoop(),
    S.comment(""),
    S.ifStep("not IsEmpty ( $err )"),
    ...fail("$err & \" Nothing on this device was changed.\""),
    S.endIf(),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ;
  [ "success" ; True ; JSONBoolean ] ;
  [ "account" ; $account ; JSONString ] ;
  [ "database" ; $database ; JSONString ] ;
  [ "tables" ; $tables ; JSONObject ] ;
  [ "warnings" ; $warnings ; JSONString ] ;
  [ "callMs" ; $callMs ; JSONNumber ] ;
  [ "downloadMs" ; $downloadMs ; JSONNumber ] ;
  [ "importMs" ; $importMs ; JSONNumber ] ;
  [ "totalMs" ; ${NOW} - $t0 ; JSONNumber ]
)`
    ),
    S.exitScript("$result"),
  ];
  return S.wrap(steps, { scriptName: SCRIPT });
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "ImportRoute.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log("\x1b[32mCopied as a whole FileMaker script -- paste into the offline file's scripts list.\x1b[0m");
      }
    );
  });
}
