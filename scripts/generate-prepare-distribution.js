// -----------------------------------------------------------------------
// Generates the "Prepare for Distribution" FileMaker script as pasteable XML.
// -----------------------------------------------------------------------
//   node ./scripts/generate-prepare-distribution
//
// Run by hand on the master copy, never from the widget, immediately before
// cloning it for the techs. It empties every table Initial Download fills,
// plus Sync_Settings, so each tech starts clean:
//
//   - No route data from whoever last used the master. A tech's device only
//     ever holds their own customers once they run Initial Download.
//   - Sync_Settings::DatabaseUUID and LastSyncUTC empty, which the
//     environment guard in UploadChanges requires of a fresh copy. Initial
//     Download recreates the record when it finishes.
//
// It keeps what the copy needs to work: HTML (the widget), Credential (the
// OData login), ProofKitApps (ProofKit's connector) and zzTableTemplate.
//
// Truncate Table cannot be undone. The script asks first, with Cancel as the
// default button, and says how many unsent edits would be lost.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const APP_NAME = "GasketsRockField";

// Base table ids from the offline file's DDR (DDRs/20261008).
const DATA_TABLES = [
  { id: 130, name: "Locations" },
  { id: 133, name: "CUSTOMER_EQUIPMENT" },
  { id: 135, name: "Address" },
  { id: 136, name: "CONj__ContactsJoin" },
  { id: 137, name: "CON_Contacts" },
  { id: 138, name: "ContactMethod" },
  { id: 141, name: "MFG_Manufacturers" },
  { id: 142, name: "Profiles" },
  { id: 132, name: "Sync_Settings" },
];

const count = (table, where = "") =>
  `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"${table}\\"${where}" ; "" ; "" ) ) )`;

function build() {
  const steps = [
    S.comment("Description: Empties all route data from this file before it is cloned"),
    S.comment("for distribution. Run by hand on the master. Cannot be undone."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-prepare-distribution.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("INITIALIZE"),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.setVar(
      "$pending",
      `${count("CUSTOMER_EQUIPMENT", ' where \\"f_pendingSync\\" = 1')} + ${count(
        "Locations",
        ' where \\"f_pendingSync\\" = 1'
      )}`
    ),
    S.setVar(
      "$records",
      DATA_TABLES.filter((t) => t.name !== "Sync_Settings")
        .map((t) => count(t.name))
        .join(" + ")
    ),
    S.comment(""),
    S.banner("CONFIRM"),
    S.comment("Cancel is button 1 and the default, so Return does not wipe the file."),
    S.showCustomDialogButtons(
      `"Clear all route data?"`,
      `"This empties every downloaded table in " & Get ( FileName ) & " (" & $records & " records) and resets the sync settings, ready to copy for the techs." & ¶ & ¶ & Case ( $pending > 0 ; $pending & " edit(s) on this copy have NOT been uploaded and will be lost." & ¶ & ¶ ; "" ) & "The widget, credentials and ProofKit records are kept. This cannot be undone."`,
      ["Cancel", "Clear Data"]
    ),
    S.ifStep(`Get ( LastMessageChoice ) ≠ 2`),
    S.exitScript(`JSONSetElement ( "{}" ; [ "cancelled" ; True ; JSONBoolean ] )`),
    S.endIf(),
    S.comment(""),
    S.banner("CLEAR"),
    S.comment("Each table is checked on its own so one failure names itself instead of"),
    S.comment("hiding behind the rest."),
    S.setVar("$failed", `""`),
    ...DATA_TABLES.flatMap((t) => [
      S.truncateTable(t.id, t.name),
      S.ifStep(`Get ( LastError ) ≠ 0`),
      S.setVar("$failed", `List ( $failed ; "${t.name} (error " & Get ( LastError ) & ")" )`),
      S.endIf(),
    ]),
    S.comment(""),
    S.banner("READY TO DISTRIBUTE?"),
    S.comment("A copy without either of these is useless to a tech, and they would only"),
    S.comment("find out in the field."),
    S.setVar(
      "$hasCredential",
      `${count("Credential", ' where \\"Name\\" = \'odata\' and \\"Value\\" is not null')} > 0`
    ),
    S.setVar(
      "$hasWidget",
      `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"HTML\\" where \\"Name\\" = ? and \\"HTML\\" is not null" ; "" ; "" ; "${APP_NAME}" ) ) ) > 0`
    ),
    S.setVar("$left", `${DATA_TABLES.map((t) => count(t.name)).join(" + ")}`),
    S.setVar(
      "$warnings",
      `List ( If ( not $hasCredential ; "No odata row in Credential -- this copy cannot download." ) ; If ( not $hasWidget ; "No ${APP_NAME} record in HTML -- this copy will open to 'Field app not installed'." ) ; If ( $left > 0 ; $left & " record(s) are still in the data tables." ) )`
    ),
    S.showCustomDialog(
      `If ( IsEmpty ( $failed ) and IsEmpty ( $warnings ) ; "Ready to distribute" ; "Not ready to distribute" )`,
      `If ( IsEmpty ( $failed ) ; "All route data cleared." ; "Could not clear:" & ¶ & $failed ) & If ( not IsEmpty ( $warnings ) ; ¶ & ¶ & $warnings ; ¶ & ¶ & "Close the file and copy it for each tech. Each copy runs Initial Download for its own route." )`
    ),
    S.exitScript(
      `JSONSetElement ( "{}" ; [ "ready" ; IsEmpty ( $failed ) and IsEmpty ( $warnings ) ; JSONBoolean ] ; [ "failed" ; $failed ; JSONString ] ; [ "warnings" ; $warnings ; JSONString ] )`
    ),
  ];
  return S.wrap(steps, { scriptName: "Prepare for Distribution" });
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "PrepareForDistribution.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log(
          "\x1b[32mCopied as a whole FileMaker script -- paste into the scripts list in Script Workspace.\x1b[0m"
        );
      }
    );
  });
}
