// -----------------------------------------------------------------------
// Generates "Download Offline App" for the UI file, GasketsRock(_Sandbox) --
// what the Download offline app button runs.
// -----------------------------------------------------------------------
//   node ./scripts/generate-ui-download-script
//
// The real work is "Download Offline App" in the data file; this hands off to
// it with Perform Script from file "Data" (the UI file's data source, path
// $$Path_Data, set by its opening script -- the sandbox UI file resolves it
// to GSR_Gaskets Rock_Sandbox). Step shape from the UI DDR's own cross-file
// Perform Script steps.
//
// Sandbox only for now. The button carries the hide condition `not inSandbox`
// (inSandbox is a custom function in the UI file); this script also refuses
// outside the sandbox, so a button copied to production does nothing.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const SCRIPT = "Download Offline App";
const performFromData = (scriptName) =>
  `<Step enable="True" id="1" name="Perform Script"><DisableStepCollapsed state="False"/><CurrentScript value="Pause"/><FileReference id="1" name="Data"><UniversalPathList>$$Path_Data</UniversalPathList></FileReference><Script id="0" name="${scriptName}"/></Step>`;

const steps = [
  S.comment("Description: Download offline app button. Hands off to Download Offline App"),
  S.comment("in the data file. Sandbox only until the field app goes live."),
  S.comment("Generated by GR_Offline/scripts/generate-ui-download-script.js."),
  S.ifStep("not inSandbox"),
  S.showCustomDialog(`"Not available yet"`, `"The field app download is only available in the sandbox for now."`),
  S.exitScript(`""`),
  S.endIf(),
  performFromData(SCRIPT),
];

const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n<Script includeInMenu="False" SiriShortcutVisible="False" runFullAccess="False" id="0" name="${SCRIPT}">\n${steps.join("\n")}\n</Script>\n</fmxmlsnippet>`;

const outPath = path.join(__dirname, "..", "fmscripts", "UIDownloadOfflineApp.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied -- paste into the scripts list of GasketsRock_Sandbox (the UI file).\x1b[0m");
    });
  });
}
