// -----------------------------------------------------------------------
// Generates the install-flow probes (fmscripts/SERVER_BUILD_DESIGN.md,
// "Install from the live file").
// -----------------------------------------------------------------------
//   node ./scripts/generate-probe-install           (offline script on clipboard)
//   node ./scripts/generate-probe-install live      (live-file script on clipboard)
//
//   zProbe - First Setup            Offline SANDBOX copy. Runs with full
//                                   access. Takes an account name as its
//                                   parameter, asks for a password, then
//                                   Add Account, Enable Account on [Guest],
//                                   Re-Login as the new account.
//                                     - No parameter: test mode. Creates
//                                       zprobe_tech, puts [Guest] back the way
//                                       it was, then asks you to sign back in
//                                       as Admin and deletes zprobe_tech.
//                                     - A real account (from the live file):
//                                       keeps the account and leaves [Guest]
//                                       deactivated, as the real setup will.
//
//   zProbe - Download Offline App   GSR_Gaskets Rock_Sandbox, run in
//                                   FileMaker Go while signed in. Saves the
//                                   file in OfflineApp::File to Documents as
//                                   INSTALL_NAME and opens it with
//                                   fmp://~/...?script=zProbe - First Setup
//                                   &param=<your account>.
//
// Schema both need (the real install flow needs them too):
//   offline copy:  Sync_Settings::zg_SetupPassword   Text, global storage
//   live file:     table OfflineApp -- Name (Text), File (Container) -- with
//                  one record holding a copy of the offline sandbox file that
//                  already contains "zProbe - First Setup".
// Run 2 (2026-10-15, FileMaker Go, from the hosted live sandbox file signed in
// as Admin): export 0 (3.9 MB to Documents), the fmp://~/ URL opened the local
// copy as [Guest] and ran First Setup with the parameter. Add Account "Admin"
// 12 (the master already has Admin), Re-Login 212, Enable Account [Guest] 212
// again -- so Guest cannot be toggled, local or hosted.
// Run 1 (2026-10-15, FileMaker Pro, offline sandbox copy -- probably the
// hosted one): Add Account 0; Enable Account on "[Guest]" 212 both ways;
// Re-Login as the new [Data Entry Only] account 9 (insufficient privileges --
// a hosted file needs fmapp to sign in, which that set lacks). The report now
// shows whether the file is hosted. Run on a local copy.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const SETUP_SCRIPT = "zProbe - First Setup";
const DOWNLOAD_SCRIPT = "zProbe - Download Offline App";
// Contains "Sandbox" so inSandbox holds, and differs from the sandbox copy
// already on the device so exporting it never overwrites that.
const INSTALL_NAME = "GasketsRockOffline_SandboxInstall.fmp12";
const TEST_ACCOUNT = "zprobe_tech";
const PASSWORD_FIELD = { table: "Sync_Settings", name: "zg_SetupPassword" };
// Built-in set; the real setup will use FieldTech (ODATA_ACCOUNT.md).
const PRIVILEGE_SET = { id: 2, name: "[Data Entry Only]" };
const GUEST = `"[Guest]"`;
const APP_TABLE = "OfflineApp";

const script = (name, steps, { fullAccess = false } = {}) =>
  `<Script includeInMenu="True" SiriShortcutVisible="False" runFullAccess="${
    fullAccess ? "True" : "False"
  }" id="0" name="${name}">\n${steps.join("\n")}\n</Script>`;
const snippet = (s) => `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n${s}\n</fmxmlsnippet>`;

const report = (pairs) =>
  `JSONSetElement ( "{}" ;\n${pairs.map(([k, v, t = "JSONString"]) => `  [ "${k}" ; ${v} ; ${t} ]`).join(" ;\n")}\n)`;

function setupScript() {
  return script(
    SETUP_SCRIPT,
    [
      S.comment("Install probe. Offline SANDBOX copy only. Safe to delete."),
      S.comment("Generated by scripts/generate-probe-install.js. Runs with full access:"),
      S.comment("Add Account, Enable Account and Delete Account require it."),
      S.setErrorCapture(true),
      S.allowUserAbort(false),
      S.ifStep("not inSandbox"),
      S.showCustomDialog(`"Sandbox only"`, `Get ( FileName ) & " is not a Sandbox copy."`),
      S.exitScript(`""`),
      S.endIf(),
      S.setVar("$account", `If ( IsEmpty ( Get ( ScriptParameter ) ) ; "${TEST_ACCOUNT}" ; Get ( ScriptParameter ) )`),
      S.setVar("$testMode", `$account = "${TEST_ACCOUNT}"`),
      S.setVar("$startedAs", "Get ( AccountName )"),
      S.comment(""),
      S.banner("ASK FOR A PASSWORD"),
      S.comment("Typed once, into a global that is cleared straight after. The password"),
      S.comment("never travels: it is not in the URL and not read from any table."),
      S.setFieldByName(`"${PASSWORD_FIELD.table}::${PASSWORD_FIELD.name}"`, `""`),
      S.showCustomDialogInput(
        `"Set up this iPad"`,
        `"Account: " & $account & ¶ & ¶ & "Choose the password you will use to open the field app on this iPad." & If ( $testMode ; ¶ & ¶ & "(Test mode -- this account is deleted again at the end.)" ; "" )`,
        ["Create Account", "Cancel"],
        [{ ...PASSWORD_FIELD, label: "Password", password: true }]
      ),
      S.setVar("$choice", "Get ( LastMessageChoice )"),
      S.setVar("$pw", `${PASSWORD_FIELD.table}::${PASSWORD_FIELD.name}`),
      S.setFieldByName(`"${PASSWORD_FIELD.table}::${PASSWORD_FIELD.name}"`, `""`),
      S.ifStep(`$choice ≠ 1 or IsEmpty ( $pw )`),
      S.exitScript(`JSONSetElement ( "{}" ; "cancelled" ; True ; JSONBoolean )`),
      S.endIf(),
      S.comment(""),
      S.banner("CREATE, SWITCH OFF GUEST, SIGN IN AS THE NEW ACCOUNT"),
      S.addAccount("$account", "$pw", PRIVILEGE_SET),
      S.setVar("$addError", "Get ( LastError )"),
      S.enableAccount("Deactivate", GUEST),
      S.setVar("$guestOffError", "Get ( LastError )"),
      S.ifStep("$testMode"),
      S.comment("Test mode puts [Guest] back. The real setup leaves it off, so the next"),
      S.comment("launch asks for the tech's account."),
      S.enableAccount("Activate", GUEST),
      S.setVar("$guestOnError", "Get ( LastError )"),
      S.endIf(),
      S.reLogin("$account", "$pw"),
      S.setVar("$reloginError", "Get ( LastError )"),
      S.setVar("$pw", `""`),
      S.setVar("$nowAs", "Get ( AccountName )"),
      S.setVar("$nowSet", "Get ( AccountPrivilegeSetName )"),
      S.setVar(
        "$report",
        report([
          ["device", "Get ( ApplicationVersion )"],
          ["file", "Get ( FileName )"],
          ["filePath", "Get ( FilePath )"],
          ["hosted", `Left ( Get ( FilePath ) ; 6 ) = "fmnet:"`, "JSONBoolean"],
          ["startedAs", "$startedAs"],
          ["account", "$account"],
          ["testMode", "$testMode", "JSONBoolean"],
          ["addError", "$addError", "JSONNumber"],
          ["guestOffError", "$guestOffError", "JSONNumber"],
          ["guestOnError", `If ( $testMode ; $guestOnError ; "left off" )`],
          ["reloginError", "$reloginError", "JSONNumber"],
          ["nowSignedInAs", "$nowAs"],
          ["privilegeSet", "$nowSet"],
        ])
      ),
      S.showCustomDialog(`"First Setup probe"`, `JSONFormatElements ( $report )`),
      S.comment(""),
      S.banner("TEST MODE: SIGN BACK IN AS ADMIN, REMOVE THE TEST ACCOUNT"),
      S.ifStep(`$testMode and $addError = 0`),
      S.showCustomDialog(
        `"Sign back in"`,
        `"Next, FileMaker asks you to sign in. Use the Admin account, so the probe can delete ${TEST_ACCOUNT}."`
      ),
      S.reLogin(),
      S.setVar("$backAs", "Get ( AccountName )"),
      S.ifStep(`$backAs ≠ "${TEST_ACCOUNT}"`),
      S.deleteAccount(`"${TEST_ACCOUNT}"`),
      S.setVar("$deleteError", "Get ( LastError )"),
      S.endIf(),
      S.showCustomDialog(
        `"Cleanup"`,
        `"Signed back in as: " & $backAs & ¶ & "Delete ${TEST_ACCOUNT}: " & If ( IsEmpty ( $deleteError ) ; "not attempted -- still signed in as it" ; "error " & $deleteError )`
      ),
      S.endIf(),
      S.exitScript("$report"),
    ],
    { fullAccess: true }
  );
}

function downloadScript() {
  return script(DOWNLOAD_SCRIPT, [
    S.comment("Install probe for the live SANDBOX file. Run in FileMaker Go while signed in."),
    S.comment("Generated by scripts/generate-probe-install.js. Safe to delete."),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.comment("The master already has an Admin account, so Add Account cannot create it"),
    S.comment("(run 1: error 12, then Re-Login 212). Signed in here as Admin, send a"),
    S.comment("throwaway name instead so the probe can still prove Add Account + Re-Login."),
    S.setVar("$account", `If ( Get ( AccountName ) = "Admin" ; "zprobe_ipad" ; Get ( AccountName ) )`),
    S.goToLayout(0, APP_TABLE),
    S.setVar("$layoutError", "Get ( LastError )"),
    S.showAllRecords(),
    S.setVar("$found", "Get ( FoundCount )"),
    S.setVar("$size", `GetContainerAttribute ( ${APP_TABLE}::File ; "filesize" )`),
    S.ifStep(`$layoutError ≠ 0 or $found = 0 or IsEmpty ( ${APP_TABLE}::File )`),
    S.showCustomDialog(
      `"Nothing to download"`,
      `"Needs an ${APP_TABLE} layout with a record whose File holds the offline sandbox copy. Layout error " & $layoutError & ", records " & $found & "."`
    ),
    S.exitScript(`""`),
    S.endIf(),
    S.comment(""),
    S.setVar("$path", `Get ( DocumentsPath ) & "${INSTALL_NAME}"`),
    S.exportFieldContents({ table: APP_TABLE, name: "File" }, "$path"),
    S.setVar("$exportError", "Get ( LastError )"),
    S.setVar(
      "$url",
      `"fmp://~/${INSTALL_NAME}?script=" & GetAsURLEncoded ( "${SETUP_SCRIPT}" ) & "&param=" & GetAsURLEncoded ( $account )`
    ),
    S.showCustomDialog(
      `"Download probe"`,
      `JSONFormatElements ( ${report([
        ["device", "Get ( ApplicationVersion )"],
        ["account", "$account"],
        ["fileSize", "$size", "JSONNumber"],
        ["path", "$path"],
        ["exportError", "$exportError", "JSONNumber"],
        ["url", "$url"],
      ])} ) & ¶ & ¶ & If ( $exportError = 0 ; "OK opens it and runs First Setup." ; "Export failed -- not opening." )`
    ),
    S.ifStep("$exportError = 0"),
    S.openURL("$url"),
    S.endIf(),
    S.exitScript(`""`),
  ]);
}

const outputs = {
  offline: { file: "ProbeInstall_Offline.xml", xml: snippet(setupScript()), where: "GasketsRockOffline_Sandbox" },
  live: { file: "ProbeInstall_Live.xml", xml: snippet(downloadScript()), where: "GSR_Gaskets Rock_Sandbox" },
};
for (const o of Object.values(outputs)) {
  const p = path.join(__dirname, "..", "fmscripts", o.file);
  fs.writeFileSync(p, o.xml);
  console.log(`\x1b[32mWrote ${path.relative(process.cwd(), p)}\x1b[0m`);
}
const pick = outputs[process.argv[2] === "live" ? "live" : "offline"];
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(pick.xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log(`\x1b[32mCopied ${pick.file} -- paste into the scripts list of ${pick.where}.\x1b[0m`);
      }
    );
  });
}
