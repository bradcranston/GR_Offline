// -----------------------------------------------------------------------
// Generates two throwaway probe scripts for GSR_Gaskets Rock_Sandbox.
// -----------------------------------------------------------------------
//   node ./scripts/generate-probe-server-export
//
// Server-build option B (fmscripts/SERVER_BUILD_DESIGN.md) rests on two
// things nobody has run on this server yet:
//
//   1. Export Records to a FileMaker (.fmp12) file under Perform Script on
//      Server, into Get ( TemporaryPath ).
//   2. MBS ( "Container.ReadFile" ) under PSoS, to get that file into a
//      container without relying on Insert File.
//
// "zProbe - Server Export" does both against Profiles (99 records, nothing
// sensitive), deletes the file, and returns every intermediate result as
// JSON. "zProbe - Run Server Export" runs it with PSoS and shows the JSON.
// Run the inner script directly on a client too: if it works there but not
// on the server, the difference is the answer.
//
// Paste into the SANDBOX data file only. Delete both once answered.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

// From DDRs/20261005 GSR_Gaskets Rock_Sandbox: layout 27 "List - Profiles"
// is on the PROFILES occurrence; field ids are from the Profiles base table.
const LAYOUT = { id: 27, name: "List - Profiles" };
const FIELDS = [
  { table: "PROFILES", id: 20, name: "__kp_Gasket_Profile" },
  { table: "PROFILES", id: 6, name: "Profile_Description" },
  { table: "PROFILES", id: 15, name: "Profile_Dimensions" },
];

const INNER = "zProbe - Server Export";
const OUTER = "zProbe - Run Server Export";

const script = (name, steps) =>
  `<Script includeInMenu="True" SiriShortcutVisible="False" runFullAccess="False" id="0" name="${name}">\n${steps.join(
    "\n"
  )}\n</Script>`;

// Run 1 (2026-10-09, FMS 22.0.6 on Linux, MBS 16.4): .fmp12 export to
// Get ( TemporaryPath ) failed with 800; Container.ReadFile exists;
// Files.DeleteFile does not (Files.Delete does).
// Run 2: .fmp12 failed with 800 in temp (which existed), Documents, and
// Documents with filelinux: -- the format, not the folder.
// Run 3: Merge (.mer) exports cleanly to both folders (2,494 bytes, header row
// of field names, UTF-16), and Files.Delete removes them. Container.ReadFile
// rejected a second argument: it is a mode, not a name.
// Run 4: Container.ReadFile with the path only.
const ATTEMPTS = [
  { key: "temp", path: `Get ( TemporaryPath ) & "probe_a.mer"` },
  { key: "documents", path: `Get ( DocumentsPath ) & "probe_b.mer"` },
];

function attempt(a) {
  const v = (n) => `$${a.key}_${n}`;
  return [
    S.comment(""),
    S.banner(`EXPORT TO ${a.key.toUpperCase()}`),
    S.setVar(v("path"), a.path),
    S.exportRecords(v("path"), FIELDS, "MRGE"),
    S.setVar(v("error"), "Get ( LastError )"),
    S.setVar(
      v("native"),
      `MBS ( "Path.FileMakerPathToNativePath" ; Substitute ( ${v("path")} ; "filelinux:" ; "" ) )`
    ),
    S.setVar(v("exists"), `MBS ( "Files.FileExists" ; ${v("native")} )`),
    S.setVar(v("size"), `MBS ( "Files.FileSize" ; ${v("native")} )`),
    S.ifStep(`IsEmpty ( $readFrom ) and ${v("exists")} = 1`),
    S.setVar("$readFrom", v("native")),
    S.endIf(),
    S.setVar(
      "$attempts",
      `JSONSetElement ( $attempts ; "${a.key}" ; JSONSetElement ( "{}" ; [ "path" ; ${v("path")} ; JSONString ] ; [ "exportError" ; ${v("error")} ; JSONNumber ] ; [ "fileExists" ; ${v("exists")} ; JSONString ] ; [ "fileSize" ; ${v("size")} ; JSONString ] ) ; JSONObject )`
    ),
  ];
}

function inner() {
  return script(INNER, [
    S.comment("Probe for the server-side build. Safe to delete."),
    S.comment("Generated by scripts/generate-probe-server-export.js."),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.setVar("$where", `If ( PatternCount ( Get ( ApplicationVersion ) ; "Server" ) ; "server" ; "client" )`),
    S.setVar("$attempts", `"{}"`),
    S.setVar("$readFrom", `""`),
    S.goToLayout(LAYOUT.id, LAYOUT.name),
    S.setVar("$layoutError", "Get ( LastError )"),
    S.showAllRecords(),
    S.setVar("$found", "Get ( FoundCount )"),
    S.comment(""),
    S.banner("MAKE SURE THE TEMP FOLDER EXISTS"),
    S.setVar("$tempNative", `MBS ( "Path.FileMakerPathToNativePath" ; Get ( TemporaryPath ) )`),
    S.setVar("$tempExistedBefore", `MBS ( "Files.DirectoryExists" ; $tempNative )`),
    S.ifStep(`$tempExistedBefore ≠ 1`),
    S.setVar("$tempCreate", `MBS ( "Files.CreateDirectory" ; $tempNative )`),
    S.endIf(),
    S.setVar("$tempExistsNow", `MBS ( "Files.DirectoryExists" ; $tempNative )`),
    ...ATTEMPTS.flatMap(attempt),
    S.comment(""),
    S.banner("READ BACK THE FIRST FILE THAT WAS WRITTEN"),
    S.ifStep(`not IsEmpty ( $readFrom )`),
    S.setVar("$file", `MBS ( "Container.ReadFile" ; $readFrom )`),
    S.comment("First lines of the file as text: the header row should be the field names."),
    S.setVar("$preview", `Left ( MBS ( "Text.ReadTextFile" ; $readFrom ; "UTF-16" ) ; 300 )`),
    S.setVar(
      "$readResult",
      `If ( PatternCount ( GetAsText ( $file ) ; "[MBS]" ) ; GetAsText ( $file ) ; "container " & GetContainerAttribute ( $file ; "filename" ) & ", " & GetContainerAttribute ( $file ; "filesize" ) & " bytes" )`
    ),
    S.elseStep(),
    S.setVar("$readResult", `"nothing to read -- no attempt wrote a file"`),
    S.endIf(),
    S.comment(""),
    S.banner("CLEAN UP"),
    S.comment("Temp is cleared with the session, but delete both: Documents is not."),
    S.setVar("$cleanup", `MBS ( "Files.Delete" ; $temp_native ) & " / " & MBS ( "Files.Delete" ; $documents_native )`),
    S.comment(""),
    S.exitScript(
      `JSONSetElement ( "{}" ;
  [ "ranOn" ; $where ; JSONString ] ;
  [ "application" ; Get ( ApplicationVersion ) ; JSONString ] ;
  [ "layoutError" ; $layoutError ; JSONNumber ] ;
  [ "foundCount" ; $found ; JSONNumber ] ;
  [ "temporaryPath" ; Get ( TemporaryPath ) ; JSONString ] ;
  [ "documentsPath" ; Get ( DocumentsPath ) ; JSONString ] ;
  [ "tempExistedBefore" ; $tempExistedBefore ; JSONString ] ;
  [ "tempCreate" ; $tempCreate ; JSONString ] ;
  [ "tempExistsNow" ; $tempExistsNow ; JSONString ] ;
  [ "attempts" ; $attempts ; JSONObject ] ;
  [ "readFile" ; $readResult ; JSONString ] ;
  [ "preview" ; $preview ; JSONString ] ;
  [ "cleanup" ; $cleanup ; JSONString ]
)`
    ),
  ]);
}

function outer() {
  return script(OUTER, [
    S.comment("Runs the probe on the server and shows what came back. Safe to delete."),
    S.comment("Generated by scripts/generate-probe-server-export.js."),
    S.setErrorCapture(true),
    S.performScriptOnServer(INNER, `""`, true),
    S.setVar("$psosError", "Get ( LastError )"),
    S.setVar("$result", "Get ( ScriptResult )"),
    S.showCustomDialog(
      `"Server export probe"`,
      `"PSoS error: " & $psosError & ¶ & ¶ & If ( IsEmpty ( $result ) ; "(no result)" ; JSONFormatElements ( $result ) )`
    ),
    S.exitScript("$result"),
  ]);
}

// Inner first, so the PSoS step resolves it by name when both are pasted.
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n${inner()}\n${outer()}\n</fmxmlsnippet>`;
const outPath = path.join(__dirname, "..", "fmscripts", "ProbeServerExport.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log(
          "\x1b[32mCopied both scripts -- paste into the scripts list of GSR_Gaskets Rock_Sandbox.\x1b[0m"
        );
      }
    );
  });
}
