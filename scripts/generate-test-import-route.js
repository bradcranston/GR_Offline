// -----------------------------------------------------------------------
// Generates "zTest - Import Route": runs Import Route for an account you type
// and shows the JSON it returns. Offline SANDBOX copy only; throwaway.
// -----------------------------------------------------------------------
//   node ./scripts/generate-test-import-route
//
// Sign in as Admin first (Guest cannot read the server credentials). The
// account must have customers assigned in the live sandbox file; "Head Office"
// is the one the probes used. Import Route REPLACES this copy's route data.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const FIELD = { table: "Sync_Settings", id: 37, name: "zg_SetupPassword" }; // a global text field, borrowed for the prompt

const steps = [
  S.comment("Test harness for Import Route. Offline SANDBOX copy only. Safe to delete."),
  S.comment("Generated by scripts/generate-test-import-route.js."),
  S.setErrorCapture(true),
  S.ifStep("not inSandbox"),
  S.showCustomDialog(`"Sandbox only"`, `Get ( FileName ) & " is not a Sandbox copy."`),
  S.exitScript(`""`),
  S.endIf(),
  S.setFieldByName(`"${FIELD.table}::${FIELD.name}"`, `"Head Office"`),
  S.showCustomDialogInput(
    `"Test Import Route"`,
    `"Replaces this copy's route with the server's for the account below." & ¶ & "Signed in as: " & Get ( AccountName )`,
    ["Run", "Cancel"],
    [{ ...FIELD, label: "Account" }]
  ),
  S.setVar("$choice", "Get ( LastMessageChoice )"),
  S.setVar("$account", `${FIELD.table}::${FIELD.name}`),
  S.setFieldByName(`"${FIELD.table}::${FIELD.name}"`, `""`),
  S.ifStep(`$choice ≠ 1 or IsEmpty ( $account )`),
  S.exitScript(`""`),
  S.endIf(),
  S.performScriptWithParam("Import Route", `JSONSetElement ( "{}" ; "account" ; $account ; JSONString )`),
  S.setVar("$result", "Get ( ScriptResult )"),
  S.showCustomDialog(`"Import Route result"`, `JSONFormatElements ( $result )`),
  S.exitScript("$result"),
];
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n<Script includeInMenu="True" SiriShortcutVisible="False" runFullAccess="False" id="0" name="zTest - Import Route">\n${steps.join("\n")}\n</Script>\n</fmxmlsnippet>`;
const outPath = path.join(__dirname, "..", "fmscripts", "TestImportRoute.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied -- paste into the offline SANDBOX copy's scripts list.\x1b[0m");
    });
  });
}
