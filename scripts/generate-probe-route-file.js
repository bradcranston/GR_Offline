// -----------------------------------------------------------------------
// Generates the device-side probe for the server build (option B).
// -----------------------------------------------------------------------
//   node ./scripts/generate-probe-route-file          (server script on clipboard)
//   node ./scripts/generate-probe-route-file device   (device script on clipboard)
//
// The server half is proven (generate-probe-server-export.js, runs 1-4). This
// tests the rest of the round trip the way the real thing will run it:
//
//   zProbe_RouteFile          GSR_Gaskets Rock_Sandbox. Exports the Profiles
//                             to Merge, reads it into a container, returns it
//                             as base64 in the script result.
//   zProbe - Import Route     The offline SANDBOX copy. Calls zProbe_RouteFile
//     File                    over the OData script endpoint with the odata
//                             credential, decodes it into
//                             Sync_Settings::zg_RouteFile, exports that to the
//                             temp folder, imports it into Profiles by field
//                             name, then deletes exactly the rows it added.
//
// Proves in one run: the odata account can call a server script; the result
// carries the file; FileMaker Go can export a container to its temp folder;
// Import Records reads the server's UTF-16 Merge file by field name.
//
// Needs one new field in the offline sandbox copy:
//   Sync_Settings::zg_RouteFile   Container, global storage
// The real Import Route needs it too.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const HOST = "https://gr.cranstonhost.com/fmi/odata/v4/";
const SANDBOX_DB = "GSR_Gaskets Rock_Sandbox";
const SERVER_SCRIPT = "zProbe_RouteFile"; // no spaces: it goes in a URL
const DEVICE_SCRIPT = "zProbe - Import Route File";

// Server: layout 27 "List - Profiles" on PROFILES (DDRs/20261005).
const SERVER_LAYOUT = { id: 27, name: "List - Profiles" };
const SERVER_FIELDS = [
  { table: "PROFILES", id: 20, name: "__kp_Gasket_Profile" },
  { table: "PROFILES", id: 6, name: "Profile_Description" },
  { table: "PROFILES", id: 15, name: "Profile_Dimensions" },
];

// Device: TO Profiles (id 1065113), layout 29 ProfilesSync (DDRs/20261008).
// Same field ids as the server, in the same order as the export's columns.
const DEVICE_LAYOUT = { id: 29, name: "ProfilesSync" };
const DEVICE_TABLE = { id: 1065113, name: "Profiles" };
const DEVICE_FIELDS = [
  { id: 20, name: "__kp_Gasket_Profile" },
  { id: 6, name: "Profile_Description" },
  { id: 15, name: "Profile_Dimensions" },
];
const ROUTE_FIELD = { table: "Sync_Settings", name: "zg_RouteFile" };

// Same as UploadChanges: status of the final response in the dumped headers.
const STATUS_CALC = `Let ( p = Position ( $headerResponse ; "HTTP/" ; Length ( $headerResponse ) ; -1 ) ; GetAsNumber ( Middle ( $headerResponse ; Position ( $headerResponse ; " " ; p ; 1 ) + 1 ; 3 ) ) )`;

const script = (name, steps) =>
  `<Script includeInMenu="True" SiriShortcutVisible="False" runFullAccess="False" id="0" name="${name}">\n${steps.join(
    "\n"
  )}\n</Script>`;
const snippet = (scripts) =>
  `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n${scripts.join(
    "\n"
  )}\n</fmxmlsnippet>`;

function serverScript() {
  return script(SERVER_SCRIPT, [
    S.comment("Probe for the server build, called over OData. Safe to delete."),
    S.comment("Generated by scripts/generate-probe-route-file.js."),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.goToLayout(SERVER_LAYOUT.id, SERVER_LAYOUT.name),
    S.setVar("$layoutError", "Get ( LastError )"),
    S.showAllRecords(),
    S.setVar("$found", "Get ( FoundCount )"),
    S.setVar("$path", `Get ( TemporaryPath ) & "route_profiles.mer"`),
    S.exportRecords("$path", SERVER_FIELDS, "MRGE"),
    S.setVar("$exportError", "Get ( LastError )"),
    S.setVar("$native", `MBS ( "Path.FileMakerPathToNativePath" ; $path )`),
    S.setVar("$file", `MBS ( "Container.ReadFile" ; $native )`),
    S.setVar("$readError", `If ( PatternCount ( GetAsText ( $file ) ; "[MBS]" ) ; GetAsText ( $file ) ; "" )`),
    S.setVar("$cleanup", `MBS ( "Files.Delete" ; $native )`),
    S.exitScript(
      `JSONSetElement ( "{}" ;
  [ "ranOn" ; Get ( ApplicationVersion ) ; JSONString ] ;
  [ "account" ; Get ( AccountName ) ; JSONString ] ;
  [ "layoutError" ; $layoutError ; JSONNumber ] ;
  [ "found" ; $found ; JSONNumber ] ;
  [ "exportError" ; $exportError ; JSONNumber ] ;
  [ "readError" ; $readError ; JSONString ] ;
  [ "filename" ; GetContainerAttribute ( $file ; "filename" ) ; JSONString ] ;
  [ "size" ; GetContainerAttribute ( $file ; "filesize" ) ; JSONNumber ] ;
  [ "base64" ; If ( IsEmpty ( $readError ) ; Base64EncodeRFC ( 4648 ; $file ) ; "" ) ; JSONString ]
)`
    ),
  ]);
}

function deviceScript() {
  return script(DEVICE_SCRIPT, [
    S.comment("Probe for the server build. Run only in the offline SANDBOX copy. Safe to delete."),
    S.comment("Generated by scripts/generate-probe-route-file.js."),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.comment(""),
    S.banner("GUARDS"),
    S.ifStep("not inSandbox"),
    S.showCustomDialog(
      `"Sandbox only"`,
      `"Run this probe in a copy whose file name contains \\"Sandbox\\". " & Get ( FileName ) & " does not."`
    ),
    S.exitScript(`""`),
    S.endIf(),
    S.ifStep("IsEmpty ( _ODataAuth ( ) )"),
    S.showCustomDialog(`"No credentials"`, `"This copy has no odata row in Credential."`),
    S.exitScript(`""`),
    S.endIf(),
    S.comment(""),
    S.banner("0. CAN THIS ACCOUNT READ THE DATABASE AT ALL?"),
    S.comment("Separates 'wrong database or credentials' from 'cannot run the script'."),
    S.setVar("$checkUrl", `${JSON.stringify(HOST + SANDBOX_DB + "/Profiles?$top=1&$select=__kp_Gasket_Profile")}`),
    S.setVar(
      "$checkCurl",
      [
        '"--X GET',
        '--H \\"Accept: application/json\\"',
        '--H \\"OData-Version: 4.0\\"',
        '--H \\"Authorization: Basic " & _ODataAuth ( ) & "\\"',
        "--dump-header $headerResponse",
        '"',
      ].join("\n")
    ),
    S.setVar("$headerResponse", `""`),
    S.insertFromURL("$checkUrl", "$checkCurl", "$checkResponse"),
    S.setVar("$checkStatus", STATUS_CALC),
    S.comment(""),
    S.banner("1. ASK THE SERVER FOR THE FILE"),
    S.setVar("$url", `${JSON.stringify(HOST + SANDBOX_DB + "/Script." + SERVER_SCRIPT)}`),
    S.setVar("$body", `JSONSetElement ( "{}" ; "scriptParameterValue" ; "" ; JSONString )`),
    S.setVar(
      "$curl",
      [
        '"--X POST',
        '--H \\"Accept: application/json\\"',
        '--H \\"OData-Version: 4.0\\"',
        '--H \\"Content-Type: application/json\\"',
        '--H \\"Authorization: Basic " & _ODataAuth ( ) & "\\"',
        "--data @$body",
        "--dump-header $headerResponse",
        '"',
      ].join("\n")
    ),
    S.setVar("$headerResponse", `""`),
    S.setVar("$startedAt", "Get ( CurrentTimeUTCMilliseconds )"),
    S.insertFromURL("$url", "$curl", "$response"),
    S.setVar("$netError", "Get ( LastError )"),
    S.setVar("$ms", "Get ( CurrentTimeUTCMilliseconds ) - $startedAt"),
    S.setVar("$status", STATUS_CALC),
    S.setVar("$scriptCode", `JSONGetElement ( $response ; "scriptResult.code" )`),
    S.setVar("$result", `JSONGetElement ( $response ; "scriptResult.resultParameter" )`),
    S.setVar("$b64", `JSONGetElement ( $result ; "base64" )`),
    S.comment(""),
    S.comment("A failed call is not JSON, and JSONGetElement then returns its own error"),
    S.comment("message -- which starts with \"?\" and is not empty. Test the status too."),
    S.setVar("$callFailed", `$netError ≠ 0 or $status < 200 or $status > 299 or IsEmpty ( $b64 ) or Left ( $b64 ; 1 ) = "?"`),
    S.ifStep("$callFailed"),
    S.setVar("$stage", `"server call failed -- see httpStatus and rawResponse"`),
    S.elseStep(),
    S.comment(""),
    S.banner("2. CONTAINER, THEN A FILE IN TEMP"),
    S.setFieldByName(`"${ROUTE_FIELD.table}::${ROUTE_FIELD.name}"`, `Base64Decode ( $b64 ; "route_profiles.mer" )`),
    S.setVar("$setError", "Get ( LastError )"),
    S.setVar("$path", `Get ( TemporaryPath ) & "route_profiles.mer"`),
    S.exportFieldContents(ROUTE_FIELD, "$path"),
    S.setVar("$exportError", "Get ( LastError )"),
    S.comment(""),
    S.banner("3. IMPORT BY FIELD NAME"),
    S.goToLayout(DEVICE_LAYOUT.id, DEVICE_LAYOUT.name),
    S.setVar("$before", "Get ( TotalRecordCount )"),
    S.importRecordsMerge("$path", DEVICE_TABLE, DEVICE_FIELDS, "Add"),
    S.setVar("$importError", "Get ( LastError )"),
    S.setVar("$imported", "Get ( FoundCount )"),
    S.setVar("$after", "Get ( TotalRecordCount )"),
    S.setVar(
      "$sample",
      `Profiles::__kp_Gasket_Profile & " | " & Profiles::Profile_Description & " | " & Profiles::Profile_Dimensions`
    ),
    S.comment(""),
    S.banner("4. REMOVE EXACTLY WHAT WAS ADDED"),
    S.comment("After an import the found set is the imported rows. Delete only when the"),
    S.comment("counts prove that -- a failed import leaves the old found set in place."),
    S.ifStep(`$importError = 0 and $imported > 0 and $after = $before + $imported`),
    S.deleteAllRecords(),
    S.setVar("$cleanup", `"removed the " & $imported & " imported rows; " & Get ( TotalRecordCount ) & " left"`),
    S.elseStep(),
    S.setVar("$cleanup", `"nothing deleted -- counts did not line up"`),
    S.endIf(),
    S.setFieldByName(`"${ROUTE_FIELD.table}::${ROUTE_FIELD.name}"`, `""`),
    S.setVar("$stage", `"done"`),
    S.endIf(),
    S.comment(""),
    S.setVar(
      "$report",
      `JSONSetElement ( "{}" ;
  [ "stage" ; $stage ; JSONString ] ;
  [ "device" ; Get ( ApplicationVersion ) ; JSONString ] ;
  [ "netError" ; $netError ; JSONNumber ] ;
  [ "httpStatus" ; $status ; JSONNumber ] ;
  [ "ms" ; $ms ; JSONNumber ] ;
  [ "scriptCode" ; $scriptCode ; JSONString ] ;
  [ "server" ; If ( $callFailed ; "" ; JSONDeleteElement ( $result ; "base64" ) ) ; JSONString ] ;
  [ "base64Length" ; If ( $callFailed ; 0 ; Length ( $b64 ) ) ; JSONNumber ] ;
  [ "readCheckStatus" ; $checkStatus ; JSONNumber ] ;
  [ "readCheckResponse" ; If ( $checkStatus < 200 or $checkStatus > 299 ; Left ( $checkResponse ; 300 ) ; "ok" ) ; JSONString ] ;
  [ "url" ; $url ; JSONString ] ;
  [ "setError" ; $setError ; JSONString ] ;
  [ "exportError" ; $exportError ; JSONString ] ;
  [ "importError" ; $importError ; JSONString ] ;
  [ "before" ; $before ; JSONString ] ;
  [ "imported" ; $imported ; JSONString ] ;
  [ "after" ; $after ; JSONString ] ;
  [ "sample" ; $sample ; JSONString ] ;
  [ "cleanup" ; $cleanup ; JSONString ] ;
  [ "rawResponse" ; If ( $callFailed ; Left ( $response ; 400 ) ; "" ) ; JSONString ]
)`
    ),
    S.showCustomDialog(`"Route file probe"`, `JSONFormatElements ( $report )`),
    S.exitScript("$report"),
  ]);
}

const outputs = {
  server: { file: "ProbeRouteFile_Server.xml", xml: snippet([serverScript()]), where: "GSR_Gaskets Rock_Sandbox" },
  device: { file: "ProbeRouteFile_Device.xml", xml: snippet([deviceScript()]), where: "the offline SANDBOX copy" },
};
for (const o of Object.values(outputs)) {
  const p = path.join(__dirname, "..", "fmscripts", o.file);
  fs.writeFileSync(p, o.xml);
  console.log(`\x1b[32mWrote ${path.relative(process.cwd(), p)}\x1b[0m`);
}

const pick = outputs[process.argv[2] === "device" ? "device" : "server"];
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(pick.xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log(`\x1b[32mCopied ${pick.file} -- paste into the scripts list of ${pick.where}.\x1b[0m`);
      }
    );
  });
}
