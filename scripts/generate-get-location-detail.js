// -----------------------------------------------------------------------
// Generates the "GetLocationDetail" FileMaker script as pasteable XML.
// -----------------------------------------------------------------------
//   node ./scripts/generate-get-location-detail
//
// Replaces the current script, which returns a hardcoded Insert Text blob
// (the Smashburger York Commons record) regardless of which location was
// tapped, and never calls the promise callback the web viewer is waiting on.
//
// The whole payload the widget needs -- location fields with equipment and
// contacts nested -- is already produced by the Locations::asJSON
// calculation, verified against the live file. So this is one ExecuteSQL
// and a callback: no layout switch, no find, no window juggling.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const WEBVIEWER = "web";

function build() {
  const steps = [
    S.comment("Description: Returns one location's full detail to the web viewer."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-get-location-detail.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("PARAMS"),
    S.comment("The web viewer's fmBridge.performScript sends callbackName / promiseID /"),
    S.comment("parameter. All three must come back out or the JS promise never settles."),
    S.setVar("$callbackName", `JSONGetElement ( Get ( ScriptParameter ) ; "callbackName" )`),
    S.setVar("$promiseID", `JSONGetElement ( Get ( ScriptParameter ) ; "promiseID" )`),
    S.setVar("$parameter", `JSONGetElement ( Get ( ScriptParameter ) ; "parameter" )`),
    S.setVar("$locationID", `JSONGetElement ( $parameter ; "__ID" )`),
    S.setVar("$webviewer", `"${WEBVIEWER}"`),
    S.comment(""),
    S.banner("INITIALIZE"),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.comment(""),
    S.ifStep(`IsEmpty ( $locationID )`),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "error" ; "GetLocationDetail was called without a location __ID." ; JSONString ] )`
    ),
    S.performJS("$webviewer", "$callbackName", ["$promiseID", "$result"]),
    S.exitScript("$result"),
    S.endIf(),
    S.comment(""),
    S.banner("FETCH"),
    S.comment("Locations::asJSON already nests CUSTOMER_EQUIPMENT and CONj__ContactsJoin,"),
    S.comment("which is exactly the shape loadLocationDetail expects."),
    S.setVar(
      "$json",
      `ExecuteSQL ( "select \\"asJSON\\" from \\"Locations\\" where \\"__ID\\" = ?" ; "" ; "" ; $locationID )`
    ),
    S.comment(""),
    S.ifStep(`IsEmpty ( $json )`),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "error" ; "Location " & $locationID & " isn't on this device. Run Initial Download while connected." ; JSONString ] )`
    ),
    S.performJS("$webviewer", "$callbackName", ["$promiseID", "$result"]),
    S.exitScript("$result"),
    S.endIf(),
    S.comment(""),
    S.banner("RETURN TO THE WEB VIEWER"),
    S.performJS("$webviewer", "$callbackName", ["$promiseID", "$json"]),
    S.exitScript("$json"),
  ];

  return S.wrap(steps, { scriptName: "GetLocationDetail" });
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "GetLocationDetail.xml");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log("\x1b[32mCopied as a whole FileMaker script -- paste into the scripts list in Script Workspace (rename the old one first).\x1b[0m");
      }
    );
  });
}
