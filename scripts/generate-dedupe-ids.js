// -----------------------------------------------------------------------
// Generates "Dedupe __ID" + "Dedupe __ID - Run on Server" for the GSR data
// file (GSR_Gaskets Rock_Sandbox first, then production).
// -----------------------------------------------------------------------
//   node ./scripts/generate-dedupe-ids
//
// The field app and UploadChanges address a record by __ID. Two server rows
// sharing one (iPad upload 2026-10-15: label 600705 exists twice under
// 2YECQBFZ54GLSJX5ZUY554J4K) means an upload edits whichever the lookup
// returns first and leaves the other stale.
//
// "Dedupe __ID", per table (Locations, CustomersEquipment):
//   1. Find __ID "!" -- the duplicates operator, indexed, so the loop only
//      walks the duplicated rows, not the whole table.
//   2. Walk that found set unsorted (creation order). The first row seen with
//      an id keeps it; every later row with the same id gets a fresh
//      uID_CreateWithNoSpaces.
//   3. Returns counts and up to 50 { key, oldID, newID } samples.
// Blank ids are skipped (Backfill __ID handles those). No dialogs, so it runs
// server-side; re-runnable -- a second run should find nothing. Locked
// records are reported, not retried.
//
// After it runs, reinstall the field app: an installed copy still holds the
// old shared ids.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");
const { tables } = require("./routeTables.json");

const SCRIPT = "Dedupe __ID";
const CALLER = "Dedupe __ID - Run on Server";
const TARGETS = [
  { label: "LOCATIONS", key: "__kp_Location" },
  { label: "EQUIPMENT", key: "__kp_CustomerEquipment" },
].map(({ label, key }) => {
  const t = tables.find((x) => x.label === label);
  if (!t) throw new Error(`routeTables.json has no ${label}`);
  return { label, key, to: t.server.to, layout: t.server.layout };
});

function dedupe({ label, key, to, layout }) {
  const id = `${to}::__ID`;
  return [
    S.comment(""),
    S.banner(label),
    S.setVar("$start", "Get ( CurrentTimeUTCMilliseconds )"),
    S.setVar("$seen", `""`),
    S.setVar("$fixed", "0"),
    S.setVar("$locked", "0"),
    S.setVar("$samples", `"[]"`),
    S.goToLayout(layout.id, layout.name),
    S.enterFindMode(),
    S.setFieldByName(`"${id}"`, `"!"`),
    S.performFindCurrent(),
    S.setVar("$found", "If ( Get ( LastError ) = 0 ; Get ( FoundCount ) ; 0 )"),
    S.ifStep("$found > 0"),
    S.goToRecordFirst(),
    S.loop(),
    S.setVar("$id", id),
    S.ifStep("not IsEmpty ( $id )"),
    S.ifStep("IsEmpty ( FilterValues ( $id ; $seen ) )"),
    S.comment("First row with this id keeps it."),
    S.setVar("$seen", "List ( $seen ; $id )"),
    S.elseStep(),
    S.setVar("$newID", "uID_CreateWithNoSpaces"),
    S.setFieldByName(`"${id}"`, "$newID"),
    S.commit(),
    S.ifStep(`Get ( LastError ) = 0`),
    S.setVar("$fixed", "$fixed + 1"),
    S.ifStep("$fixed ≤ 50"),
    S.setVar(
      "$samples",
      `JSONSetElement ( $samples ; "[" & ( $fixed - 1 ) & "]" ; JSONSetElement ( "{}" ; [ "key" ; ${to}::${key} ; JSONNumber ] ; [ "oldID" ; $id ; JSONString ] ; [ "newID" ; $newID ; JSONString ] ) ; JSONObject )`
    ),
    S.endIf(),
    S.elseStep(),
    S.setVar("$locked", "$locked + 1"),
    S.endIf(),
    S.endIf(),
    S.endIf(),
    S.goToRecordNextExit(),
    S.endLoop(),
    S.endIf(),
    S.setVar(
      "$result",
      `JSONSetElement ( $result ; "${label}" ; JSONSetElement ( "{}" ; [ "rowsInDuplicateGroups" ; $found ; JSONNumber ] ; [ "distinctIDs" ; ValueCount ( $seen ) ; JSONNumber ] ; [ "reassigned" ; $fixed ; JSONNumber ] ; [ "lockedSkipped" ; $locked ; JSONNumber ] ; [ "ms" ; Get ( CurrentTimeUTCMilliseconds ) - $start ; JSONNumber ] ; [ "samples" ; $samples ; JSONArray ] ) ; JSONObject )`
    ),
  ];
}

const steps = [
  S.comment("Description: Gives every row after the first in a group of duplicate __IDs"),
  S.comment("a new id, in Locations and CustomersEquipment. Server-safe; re-runnable."),
  S.comment("#################### #"),
  S.comment("Generated by GR_Offline/scripts/generate-dedupe-ids.js -- edit that, not this."),
  S.comment("#################### #"),
  S.setErrorCapture(true),
  S.allowUserAbort(false),
  S.setVar("$result", `JSONSetElement ( "{}" ; "file" ; Get ( FileName ) ; JSONString )`),
  ...TARGETS.flatMap(dedupe),
  S.exitScript("$result"),
];

const callerSteps = [
  S.comment("Runs Dedupe __ID on the server and shows what it did."),
  S.comment("Generated by GR_Offline/scripts/generate-dedupe-ids.js."),
  S.setErrorCapture(true),
  S.showCustomDialogButtons(
    `"Dedupe __ID"`,
    `"Give a new __ID to every duplicate (all but the oldest copy) in Locations and CustomersEquipment in " & Get ( FileName ) & "?" & ¶ & ¶ & "Runs on the server. Reinstall the field app afterwards."`,
    ["Cancel", "Run"]
  ),
  S.ifStep("Get ( LastMessageChoice ) ≠ 2"),
  S.exitScript(`""`),
  S.endIf(),
  S.performScriptOnServer(SCRIPT, `""`, true),
  S.setVar("$error", "Get ( LastError )"),
  S.setVar("$result", "Get ( ScriptResult )"),
  S.showCustomDialog(
    `"Dedupe __ID"`,
    `If ( $error ≠ 0 ; "Perform Script on Server error " & $error & ¶ & ¶ ; "" ) & JSONFormatElements ( JSONDeleteElement ( JSONDeleteElement ( $result ; "LOCATIONS.samples" ) ; "EQUIPMENT.samples" ) )`
  ),
  S.exitScript("$result"),
];

const script = (name, body) =>
  `<Script includeInMenu="False" SiriShortcutVisible="False" runFullAccess="True" id="0" name="${name}">\n${body.join("\n")}\n</Script>`;
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n${script(SCRIPT, steps)}\n${script(CALLER, callerSteps)}\n</fmxmlsnippet>`;

const outPath = path.join(__dirname, "..", "fmscripts", "DedupeIds.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied -- paste into the scripts list of GSR_Gaskets Rock_Sandbox.\x1b[0m");
    });
  });
}
