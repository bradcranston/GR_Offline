// -----------------------------------------------------------------------
// Generates the "SaveLocation" FileMaker script as pasteable XML.
// -----------------------------------------------------------------------
//   node ./scripts/generate-save-location
//
// The Locations counterpart to SaveEquipmentList: commits a tech's edits
// into the local Locations table and flags the row for upload. No network.
//
// Field choices are forced by the schema, not preference:
//   - Location_Name is auto-entered from LocationName_Brand / _Identifier /
//     _Number, so the form edits those three. Writing Location_Name directly
//     would be overwritten on the next commit.
//   - VisitNextDate is auto-entered from VisitLast + VisitNext, so the
//     tech edits VisitNext (weeks) and the date follows.
//   - ShipAddress1 and Pricing_ID are lookups from related records. They
//     would appear to save and then revert, so they are not writable.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const S = require("./fmSteps");

const TO = "Locations";
const LAYOUT = { id: 5, name: "LocationsSync" };
const WEBVIEWER = "web";

const WRITABLE_FIELDS = [
  "LocationName_Brand",
  "LocationName_Identifier",
  "LocationName_Number",
  "PhysicalAddress1",
  "PhysicalAddress2",
  "PhysicalCity",
  "PhysicalState",
  "PhysicalZip",
  "VisitNext",
  "Comments",
];

function fail(condition, message) {
  return [
    S.ifStep(condition),
    S.setVar("$result", `JSONSetElement ( "{}" ; [ "error" ; ${message} ; JSONString ] )`),
    ...S.callBack(),
    S.exitScript("$result"),
    S.endIf(),
  ];
}

function build() {
  const steps = [
    S.comment("Description: Commits a location edit from the web viewer into the local"),
    S.comment("table and flags it for upload. Never touches the network."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-save-location.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("PARAMS"),
    S.setErrorCapture(true),
    S.comment("Work in a card so the Home layout and its web viewer never unload."),
    S.workWindow(LAYOUT),
    S.allowUserAbort(false),
    S.setVar("$webviewer", `"${WEBVIEWER}"`),
    S.setVar("$callbackName", `JSONGetElement ( Get ( ScriptParameter ) ; "callbackName" )`),
    S.setVar("$promiseID", `JSONGetElement ( Get ( ScriptParameter ) ; "promiseID" )`),
    S.setVar("$parameter", `JSONGetElement ( Get ( ScriptParameter ) ; "parameter" )`),
    S.setVar("$locationID", `JSONGetElement ( $parameter ; "__ID" )`),
    S.setVar("$isNew", `JSONGetElement ( $parameter ; "isNew" ) = true`),
    S.setVar("$customer", `JSONGetElement ( $parameter ; "_kf_Customer" )`),
    S.comment(""),
    ...fail(`IsEmpty ( $locationID )`, `"SaveLocation was called without an __ID."`),
    S.comment(""),
    S.banner("FIND OR CREATE"),
    S.goToLayout(LAYOUT.id, LAYOUT.name),
    S.findBy(TO, "__ID", "$locationID"),
    S.setVar("$found", `Get ( LastError ) = 0`),
    S.comment(""),
    S.ifStep(`not $found and not $isNew`),
    S.comment("An edit to something that isn't on this device. Better to say so than"),
    S.comment("to silently create a half-populated duplicate location."),
    ...fail(
      "True",
      `"Location " & $locationID & " isn't on this device. Run Initial Download and try again."`
    ),
    S.endIf(),
    S.comment(""),
    S.ifStep(`not $found`),
    ...fail(
      `IsEmpty ( $customer )`,
      `"A new location needs a customer before it can be saved."`
    ),
    S.comment(""),
    S.comment("__kp_Location is assigned by the server. A row created here takes a"),
    S.comment("negative key instead: the server only ever issues positives, so a local"),
    S.comment("key can never collide with a real one, and any negative value reads as"),
    S.comment("'not uploaded yet'. UploadChanges swaps in the real key and repoints the"),
    S.comment("location's equipment straight after the create."),
    S.comment(""),
    S.comment("Assigned here rather than by an auto-enter serial because FileMaker"),
    S.comment("serials cannot count down -- the increment must be positive."),
    S.setVar(
      "$localKey",
      `Let ( m = GetAsNumber ( ExecuteSQL ( "select min ( \\"__kp_Location\\" ) from \\"${TO}\\" where \\"__kp_Location\\" < 0" ; "" ; "" ) ) ; If ( m < 0 ; m - 1 ; -1 ) )`
    ),
    S.newRecord(),
    S.setFieldByName(`"${TO}::__ID"`, `$locationID`),
    S.setFieldByName(`"${TO}::__kp_Location"`, `$localKey`),
    S.setFieldByName(`"${TO}::_kf_Customer"`, `$customer`),
    S.setFieldByName(`"${TO}::z_syncAction"`, `"create"`),
    S.endIf(),
    S.comment(""),
    S.ifStep(`IsEmpty ( ${TO}::z_syncAction )`),
    S.setFieldByName(`"${TO}::z_syncAction"`, `"update"`),
    S.endIf(),
    S.comment(""),
    S.banner("APPLY THE EDITS"),
    S.comment("Only these fields. Location_Name and VisitNextDate are auto-entered"),
    S.comment("from other fields, and ShipAddress1 / Pricing_ID are lookups."),
    ...WRITABLE_FIELDS.flatMap((f) => [
      S.ifStep(`JSONGetElement ( $parameter ; "${f}" ) ≠ "?"`),
      S.setFieldByName(`"${TO}::${f}"`, `JSONGetElement ( $parameter ; "${f}" )`),
      S.endIf(),
    ]),
    S.comment(""),
    S.setFieldByName(`"${TO}::f_pendingSync"`, "1"),
    S.setFieldByName(`"${TO}::z_localModTimestamp"`, `Get ( CurrentTimestamp )`),
    S.commit(),
    ...fail(
      `Get ( LastError ) ≠ 0`,
      `"Could not save this location (FileMaker error " & Get ( LastError ) & ")."`
    ),
    S.comment(""),
    S.banner("RETURN TO THE WEB VIEWER"),
    S.comment("asJSON is the same shape GetLocationDetail returns, so the widget can"),
    S.comment("re-render from it directly."),
    S.setVar("$json", `${TO}::asJSON`),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "success" ; True ; JSONBoolean ] ; [ "created" ; not $found ; JSONBoolean ] ; [ "location" ; $json ; JSONObject ] )`
    ),
    ...S.callBack(),
    S.exitScript("$result"),
  ];
  return S.wrap(steps, { scriptName: "SaveLocation" });
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "SaveLocation.xml");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const { spawn, exec } = require("child_process");
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied as a whole FileMaker script -- paste into the offline file's scripts list (rename the old one first).\x1b[0m");
    });
  });
}
