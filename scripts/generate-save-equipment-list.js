// -----------------------------------------------------------------------
// Generates the "SaveEquipmentList" FileMaker script as pasteable XML.
// -----------------------------------------------------------------------
//   node ./scripts/generate-save-equipment-list
//
// This script does NOT talk to the server. It commits the tech's equipment
// edits into the local CUSTOMER_EQUIPMENT table and flags them for a later
// upload, so saving always succeeds regardless of connectivity. The network
// half is a separate "Upload Changes" script -- see fmscripts/UPLOAD_DESIGN.md.
//
// Requires the schema changes listed in fmscripts/SCHEMA_CHANGES.md.
//
// Called from the widget as:
//   performScript ( "SaveEquipmentList" ; { __ID: <location __ID>,
//                                           equipment: [ { __ID: <uuid>, isNew?: true, ... } ] } )
// Returns:
//   { success: true, saved: n, created: n, deleted: n, pendingCount: n,
//     missing: [ <__ID>, ... ], equipment: [ ... ] }
//
// Creates follow SaveLocation: a row is only created when the widget says
// it is new (isNew), and it takes a negative __kp_CustomerEquipment. A row
// the widget thinks exists but this device doesn't have is reported in
// `missing`, not recreated -- that is a row the office deleted, and
// recreating it would upload it again.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const LAYOUT = { id: 7, name: "EquipmentSync" };
const TO = "CUSTOMER_EQUIPMENT";
const WEBVIEWER = "web";

// Only these fields are written from the incoming JSON. An explicit list
// beats iterating the payload's keys: a calculation or summary field that
// slipped into the payload would error on Set Field By Name, and a renamed
// field fails loudly here instead of silently not saving.
const DATE_FIELDS = ["Date_Gasket_Installed"];
const WRITABLE_FIELDS = [
  "Label_Number",
  "ProductType",
  "Manufacturer",
  "Refrigerator_Type",
  "Equipment_Location_Description",
  "Gasket_Profile",
  "Door",
  "DoorOption",
  "InvertedProfile",
  "NoMagnet",
  "Height",
  "Width",
  "Qty",
  "gasketLinearSub_Ft",
  "Item_Note",
  "Custom_Price",
  "Date_Gasket_Installed",
  "f_backerRodNeeded",
  "f_fillerNeeded",
  "f_substitutePart",
];

function fail(condition, message) {
  return [
    S.ifStep(condition),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "error" ; ${message} ; JSONString ] )`
    ),
    ...S.callBack(),
    S.exitScript("$result"),
    S.endIf(),
  ];
}

function build() {
  const steps = [
    S.comment("Description: Commits equipment edits from the web viewer into the local"),
    S.comment("table and flags them for upload. Never touches the network."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-save-equipment-list.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("INITIALIZE"),
    S.setErrorCapture(true),
    S.comment("Work in a card so the Home layout and its web viewer never unload."),
    S.workWindow(LAYOUT),
    S.allowUserAbort(false),
    S.setVar("$webviewer", `"${WEBVIEWER}"`),
    S.setVar("$callbackName", `JSONGetElement ( Get ( ScriptParameter ) ; "callbackName" )`),
    S.setVar("$promiseID", `JSONGetElement ( Get ( ScriptParameter ) ; "promiseID" )`),
    S.setVar("$parameter", `JSONGetElement ( Get ( ScriptParameter ) ; "parameter" )`),
    S.setVar("$locationID", `JSONGetElement ( $parameter ; "__ID" )`),
    S.setVar("$equipment", `JSONGetElement ( $parameter ; "equipment" )`),
    S.setVar("$saved", "0"),
    S.setVar("$created", "0"),
    S.setVar("$deleted", "0"),
    S.setVar("$missing", `"[]"`),
    S.setVar("$incomingIDs", `""`),
    S.comment(""),
    ...fail(`IsEmpty ( $locationID )`, `"SaveEquipmentList was called without a location __ID."`),
    S.comment(""),
    S.banner("RESOLVE THE LOCATION"),
    S.comment("Equipment is keyed to the numeric __kp_Location, but the web viewer"),
    S.comment("works in terms of the location's text __ID."),
    S.setVar(
      "$kpLocation",
      `ExecuteSQL ( "select \\"__kp_Location\\" from \\"Locations\\" where \\"__ID\\" = ?" ; "" ; "" ; $locationID )`
    ),
    ...fail(
      `IsEmpty ( $kpLocation )`,
      `"No local record for location " & $locationID & ". Run Initial Download and try again."`
    ),
    S.comment(""),
    S.banner("UPSERT EACH EQUIPMENT ROW"),
    S.goToLayout(LAYOUT.id, LAYOUT.name),
    S.setVar("$i", "0"),
    S.loop(),
    S.setVar("$row", `JSONGetElement ( $equipment ; "[" & $i & "]" )`),
    S.exitLoopIf(`IsEmpty ( $row ) or $row = "?"`),
    S.setVar("$rowID", `JSONGetElement ( $row ; "__ID" )`),
    S.setVar("$rowIsNew", `JSONGetElement ( $row ; "isNew" ) = true`),
    S.setVar("$rowIsChanged", `JSONGetElement ( $row ; "isChanged" ) = true`),
    S.comment(""),
    S.comment("A row with no __ID predates the identity change. It gets one here so it"),
    S.comment("can be echoed back, but unless it is also marked isNew it won't be found"),
    S.comment("and lands in $missing -- which is right: creating it would duplicate a"),
    S.comment("row this device already holds under a different identity."),
    S.ifStep(`IsEmpty ( $rowID )`),
    S.setVar("$rowID", `uID_CreateWithNoSpaces`),
    S.endIf(),
    S.setVar("$incomingIDs", `List ( $incomingIDs ; $rowID )`),
    S.comment(""),
    S.comment("Write the id back into the array being echoed to the web viewer, so a"),
    S.comment("row that arrived without one adopts this id instead of being handed a"),
    S.comment("fresh one on the next save."),
    S.setVar(
      "$equipment",
      `JSONSetElement ( $equipment ; "[" & $i & "]__ID" ; $rowID ; JSONString )`
    ),
    S.comment(""),
    S.findBy(TO, "__ID", "$rowID"),
    S.setVar("$found", `Get ( LastError ) = 0`),
    S.comment(""),
    S.ifStep(`not $found and not $rowIsNew`),
    S.comment("An edit to a row that isn't on this device -- most likely deleted in the"),
    S.comment("office and purged by Initial Download. Report it rather than silently"),
    S.comment("recreating it; the rest of the list still saves."),
    S.setVar(
      "$missing",
      `JSONSetElement ( $missing ; "[" & ValueCount ( JSONListKeys ( $missing ; "" ) ) & "]" ; $rowID ; JSONString )`
    ),
    S.elseStep(),
    S.comment("Untouched rows are only here so removals can be detected (MARK REMOVED"),
    S.comment("ROWS); writing them would queue the whole location for upload."),
    S.ifStep(`not $found or $rowIsNew or $rowIsChanged`),
    S.ifStep(`not $found`),
    S.comment("New row created in the field."),
    S.comment(""),
    S.comment("__kp_CustomerEquipment is assigned by the server. The offline file's own"),
    S.comment("serial fires on New Record, but its range came with the copy of"),
    S.comment("production this file was cloned from -- a positive local key would sit in"),
    S.comment("the server's upcoming range. Overwrite it with a negative key, as"),
    S.comment("SaveLocation does: never a collision, and negative reads as 'not uploaded"),
    S.comment("yet'. UploadChanges writes the real key back after the POST."),
    S.setVar(
      "$localKey",
      `Let ( m = GetAsNumber ( ExecuteSQL ( "select min ( \\"__kp_CustomerEquipment\\" ) from \\"${TO}\\" where \\"__kp_CustomerEquipment\\" < 0" ; "" ; "" ) ) ; If ( m < 0 ; m - 1 ; -1 ) )`
    ),
    S.newRecord(),
    S.setFieldByName(`"${TO}::__ID"`, `$rowID`),
    S.setFieldByName(`"${TO}::__kp_CustomerEquipment"`, `$localKey`),
    S.setFieldByName(`"${TO}::_kf_Location"`, `$kpLocation`),
    S.setFieldByName(`"${TO}::z_syncAction"`, `"create"`),
    S.setVar("$created", "$created + 1"),
    S.endIf(),
    S.comment(""),
    S.ifStep(`IsEmpty ( ${TO}::z_syncAction )`),
    S.setFieldByName(`"${TO}::z_syncAction"`, `"update"`),
    S.endIf(),
    S.comment(""),
    S.comment("Dates arrive as YYYY-MM-DD (GetLocationDetail, <input type=date>). Set raw"),
    S.comment("into a date field that is not a date -- it uploaded as \"?-0-0\" and the"),
    S.comment("server refused the row (iPad 2026-10-15) -- so build the date explicitly."),
    ...WRITABLE_FIELDS.flatMap((field) => [
      S.ifStep(`JSONGetElement ( $row ; "${field}" ) ≠ "?"`),
      S.setFieldByName(
        `"${TO}::${field}"`,
        DATE_FIELDS.includes(field)
          ? `Let ( v = JSONGetElement ( $row ; "${field}" ) ; Case ( IsEmpty ( v ) ; "" ; Length ( v ) = 10 and Middle ( v ; 5 ; 1 ) = "-" ; Date ( Middle ( v ; 6 ; 2 ) ; Middle ( v ; 9 ; 2 ) ; Left ( v ; 4 ) ) ; GetAsDate ( v ) ) )`
          : `JSONGetElement ( $row ; "${field}" )`
      ),
      S.endIf(),
    ]),
    S.comment(""),
    S.setFieldByName(`"${TO}::f_pendingSync"`, "1"),
    S.setFieldByName(`"${TO}::z_localModTimestamp"`, `Get ( CurrentTimestamp )`),
    S.commit(),
    ...fail(
      `Get ( LastError ) ≠ 0`,
      `"Could not save equipment row " & $rowID & " (FileMaker error " & Get ( LastError ) & "). No further rows were saved."`
    ),
    S.setVar("$saved", "$saved + 1"),
    S.endIf(),
    S.endIf(),
    S.setVar("$i", "$i + 1"),
    S.endLoop(),
    S.comment(""),
    S.banner("MARK REMOVED ROWS"),
    S.comment("Anything held locally for this location that the web viewer no longer"),
    S.comment("lists was deleted in the field. The row is flagged rather than deleted:"),
    S.comment("the server still has to be told, and the record is the queue entry."),
    S.setVar(
      "$localIDs",
      `ExecuteSQL ( "select \\"__ID\\" from \\"${TO}\\" where \\"_kf_Location\\" = ? and ( \\"z_syncAction\\" is null or \\"z_syncAction\\" <> ? )" ; "" ; "" ; $kpLocation ; "delete" )`
    ),
    S.setVar("$j", "0"),
    S.loop(),
    S.setVar("$j", "$j + 1"),
    S.setVar("$localID", `GetValue ( $localIDs ; $j )`),
    S.exitLoopIf(`IsEmpty ( $localID )`),
    S.ifStep(`IsEmpty ( FilterValues ( $localID ; $incomingIDs ) )`),
    S.findBy(TO, "__ID", "$localID"),
    S.ifStep(`Get ( LastError ) = 0`),
    S.setFieldByName(`"${TO}::z_syncAction"`, `"delete"`),
    S.setFieldByName(`"${TO}::f_pendingSync"`, "1"),
    S.setFieldByName(`"${TO}::z_localModTimestamp"`, `Get ( CurrentTimestamp )`),
    S.commit(),
    S.setVar("$deleted", "$deleted + 1"),
    S.endIf(),
    S.endIf(),
    S.endLoop(),
    S.comment(""),
    S.banner("RETURN TO THE WEB VIEWER"),
    S.comment("The equipment array is echoed back so the widget can adopt any __ID"),
    S.comment("this script assigned to a row that arrived without one. pendingCount is"),
    S.comment("the same count GetLocationList returns, so the Upload badge stays true."),
    S.setVar(
      "$pendingCount",
      `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"${TO}\\" where \\"f_pendingSync\\" = 1" ; "" ; "" ) ) ) + Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"Locations\\" where \\"f_pendingSync\\" = 1" ; "" ; "" ) ) )`
    ),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "success" ; True ; JSONBoolean ] ; [ "saved" ; $saved ; JSONNumber ] ; [ "created" ; $created ; JSONNumber ] ; [ "deleted" ; $deleted ; JSONNumber ] ; [ "pendingCount" ; $pendingCount ; JSONNumber ] ; [ "missing" ; $missing ; JSONArray ] ; [ "equipment" ; $equipment ; JSONArray ] )`
    ),
    ...S.callBack(),
    S.exitScript("$result"),
  ];

  return S.wrap(steps, { scriptName: "SaveEquipmentList" });
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "SaveEquipmentList.xml");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log("\x1b[32mCopied as a whole FileMaker script -- paste into the scripts list in Script Workspace (rename the old one first).\x1b[0m");
      }
    );
  });
}
