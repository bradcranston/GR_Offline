// -----------------------------------------------------------------------
// Generates "zTest - Field App State": why is the web viewer empty?
// -----------------------------------------------------------------------
//   node ./scripts/generate-test-app-state
//
// Paste into the offline master BEFORE duplicating it into OfflineApp, so the
// installed copy has it. Run it on the iPad from the Scripts menu when the
// screen shows only "?" (an empty web viewer). It reports what Startup decides
// on, then runs Startup and reports again. Runs with full access so it can
// read everything whoever is signed in. Throwaway.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const STATE = `JSONSetElement ( "{}" ;
  [ "account" ; Get ( AccountName ) ; JSONString ] ;
  [ "privilegeSet" ; Get ( AccountPrivilegeSetName ) ; JSONString ] ;
  [ "file" ; Get ( FileName ) ; JSONString ] ;
  [ "hosted" ; Left ( Get ( FilePath ) ; 6 ) = "fmnet:" ; JSONBoolean ] ;
  [ "settingsRows" ; ExecuteSQL ( "select count(*) from \\"Sync_Settings\\"" ; "" ; "" ) ; JSONString ] ;
  [ "initialized" ; ExecuteSQL ( "select \\"Initialized\\" from \\"Sync_Settings\\"" ; "" ; "" ) ; JSONString ] ;
  [ "htmlNames" ; Substitute ( ExecuteSQL ( "select \\"Name\\" from \\"HTML\\"" ; "" ; "" ) ; ¶ ; ", " ) ; JSONString ] ;
  [ "widgetLength" ; Length ( ExecuteSQL ( "select \\"HTML\\" from \\"HTML\\" where \\"Name\\" = ?" ; "" ; "" ; "GasketsRockField" ) ) ; JSONNumber ] ;
  [ "locations" ; ExecuteSQL ( "select count(*) from \\"Locations\\"" ; "" ; "" ) ; JSONString ] ;
  [ "equipment" ; ExecuteSQL ( "select count(*) from \\"CUSTOMER_EQUIPMENT\\"" ; "" ; "" ) ; JSONString ] ;
  [ "layout" ; Get ( LayoutName ) ; JSONString ] ;
  [ "webViewerSourceLength" ; Length ( GetLayoutObjectAttribute ( "web" ; "source" ) ) ; JSONNumber ]
)`;

const steps = [
  S.comment("Diagnostic for an empty web viewer. Safe to delete."),
  S.comment("Generated by scripts/generate-test-app-state.js."),
  S.setErrorCapture(true),
  S.goToLayout(19, "Home"),
  S.setVar("$before", STATE),
  S.showCustomDialogButtons(
    `"Field app state"`,
    `JSONFormatElements ( $before ) & ¶ & ¶ & "Run Startup now and report again?"`,
    ["Run Startup", "Close"]
  ),
  S.ifStep("Get ( LastMessageChoice ) = 1"),
  S.performScript(0, "Startup"),
  S.setVar("$startupResult", "Get ( ScriptResult )"),
  S.setVar("$after", `JSONSetElement ( ${STATE} ; "startupResult" ; $startupResult ; JSONString )`),
  S.showCustomDialog(`"After Startup"`, "JSONFormatElements ( $after )"),
  S.endIf(),
];
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n<Script includeInMenu="True" SiriShortcutVisible="False" runFullAccess="True" id="0" name="zTest - Field App State">\n${steps.join("\n")}\n</Script>\n</fmxmlsnippet>`;
const outPath = path.join(__dirname, "..", "fmscripts", "TestAppState.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied -- paste into the offline master's scripts list (after Startup exists).\x1b[0m");
    });
  });
}
