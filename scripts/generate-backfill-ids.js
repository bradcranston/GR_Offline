// -----------------------------------------------------------------------
// Generates "Backfill __ID" + "Backfill __ID - Run on Server" for the GSR
// data file (GSR_Gaskets Rock_Sandbox first, then production).
// -----------------------------------------------------------------------
//   node ./scripts/generate-backfill-ids
//
// Locations and CustomersEquipment auto-enter __ID on creation, but rows that
// predate the field are blank. The field app matches every save and upload on
// __ID, so a blank one makes SaveEquipmentList report the row "missing" (iPad
// test 2026-10-15: 45 of 127 rows at SaltGrass / Research Austin).
//
// "Backfill __ID" finds __ID = empty in each table and fills it with
// uID_CreateWithNoSpaces via Replace Field Contents (evaluated per record).
// No dialogs, so it runs server-side. Records locked by a user are skipped by
// Replace; the result counts what is still blank so it can be re-run. Safe to
// run repeatedly -- only blank ids are touched.
//
// "Backfill __ID - Run on Server" calls it with Perform Script on Server and
// shows the result. Both paste together; the callee is first in the snippet.
//
// After it runs, reinstall the field app so the route carries the new ids.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");
const { tables } = require("./routeTables.json");

const SCRIPT = "Backfill __ID";
const CALLER = "Backfill __ID - Run on Server";
const LABELS = ["LOCATIONS", "EQUIPMENT"]; // the two tables the field app syncs by __ID

const targets = LABELS.map((label) => {
  const t = tables.find((x) => x.label === label);
  const f = t.fields.find((x) => x.name === "__ID");
  if (!t || !f) throw new Error(`routeTables.json has no __ID for ${label}`);
  return { label, to: t.server.to, layout: t.server.layout, field: { table: t.server.to, id: f.server, name: "__ID" } };
});

const findBlank = (to) => [
  S.enterFindMode(),
  S.setFieldByName(`"${to}::__ID"`, `"="`),
  S.performFindCurrent(),
];

function backfill({ label, to, layout, field }) {
  return [
    S.comment(""),
    S.banner(label),
    S.setVar("$start", "Get ( CurrentTimeUTCMilliseconds )"),
    S.goToLayout(layout.id, layout.name),
    ...findBlank(to),
    S.setVar("$found", "If ( Get ( LastError ) = 0 ; Get ( FoundCount ) ; 0 )"),
    S.ifStep("$found > 0"),
    S.replaceFieldContents(field, "uID_CreateWithNoSpaces"),
    S.setVar("$replaceError", "Get ( LastError )"),
    S.commit(),
    S.comment("Count what is still blank -- locked records are skipped by Replace."),
    ...findBlank(to),
    S.setVar("$remaining", "If ( Get ( LastError ) = 0 ; Get ( FoundCount ) ; 0 )"),
    S.elseStep(),
    S.setVar("$replaceError", "0"),
    S.setVar("$remaining", "0"),
    S.endIf(),
    S.setVar(
      "$result",
      `JSONSetElement ( $result ; "${label}" ; JSONSetElement ( "{}" ; [ "blankBefore" ; $found ; JSONNumber ] ; [ "stillBlank" ; $remaining ; JSONNumber ] ; [ "replaceError" ; $replaceError ; JSONNumber ] ; [ "ms" ; Get ( CurrentTimeUTCMilliseconds ) - $start ; JSONNumber ] ) ; JSONObject )`
    ),
  ];
}

const steps = [
  S.comment("Description: Fills blank __ID in Locations and CustomersEquipment so the"),
  S.comment("offline field app can match them. Server-safe (no dialogs); re-runnable."),
  S.comment("#################### #"),
  S.comment("Generated by GR_Offline/scripts/generate-backfill-ids.js -- edit that, not this."),
  S.comment("#################### #"),
  S.setErrorCapture(true),
  S.allowUserAbort(false),
  S.setVar("$result", `JSONSetElement ( "{}" ; "file" ; Get ( FileName ) ; JSONString )`),
  ...targets.flatMap(backfill),
  S.exitScript("$result"),
];

const callerSteps = [
  S.comment("Runs Backfill __ID on the server and shows what it did."),
  S.comment("Generated by GR_Offline/scripts/generate-backfill-ids.js."),
  S.setErrorCapture(true),
  S.showCustomDialogButtons(
    `"Backfill __ID"`,
    `"Fill every blank __ID in Locations and CustomersEquipment in " & Get ( FileName ) & "?" & ¶ & ¶ & "Runs on the server; only blank ids are changed."`,
    ["Cancel", "Run"]
  ),
  S.ifStep("Get ( LastMessageChoice ) ≠ 2"),
  S.exitScript(`""`),
  S.endIf(),
  S.performScriptOnServer(SCRIPT, `""`, true),
  S.setVar("$error", "Get ( LastError )"),
  S.setVar("$result", "Get ( ScriptResult )"),
  S.showCustomDialog(
    `"Backfill __ID"`,
    `If ( $error ≠ 0 ; "Perform Script on Server error " & $error & ¶ & ¶ ; "" ) & JSONFormatElements ( $result )`
  ),
  S.exitScript("$result"),
];

const script = (name, body) =>
  `<Script includeInMenu="False" SiriShortcutVisible="False" runFullAccess="True" id="0" name="${name}">\n${body.join("\n")}\n</Script>`;
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n${script(SCRIPT, steps)}\n${script(CALLER, callerSteps)}\n</fmxmlsnippet>`;

const outPath = path.join(__dirname, "..", "fmscripts", "BackfillIds.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied -- paste into the scripts list of GSR_Gaskets Rock_Sandbox.\x1b[0m");
    });
  });
}
