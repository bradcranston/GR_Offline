// -----------------------------------------------------------------------
// Generates "Startup" and "GetLocationList".
// -----------------------------------------------------------------------
//   node ./scripts/generate-startup
//
//   Startup          -> set as the file's OnFirstWindowOpen trigger.
//                       Loads the widget HTML into the web viewer and
//                       stops there. Self-contained: the old "Load Widget"
//                       was deleted along with the rest of the template's
//                       scripts, and splitting two steps across two
//                       scripts only bought a reference to break.
//   GetLocationList  -> what the widget calls the moment it is running.
//                       Returns the list plus the state the widget needs
//                       to decide what to render.
//
// Why the widget pulls instead of FileMaker pushing: the deleted sketch was
// Set Web Viewer -> Pause [1/2] -> Perform JavaScript. Half a second is a
// guess, and when it is wrong on a slow iPad the tech gets an empty list
// with no error. A pull cannot race: the widget only asks once it exists.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const S = require("./fmSteps");

const WEBVIEWER = "web";
const WIDGET_LAYOUT = { id: 19, name: "Home" };
const APP_NAME = "GasketsRockField";

// ---------------------------------------------------------------- //
// GetLocationList                                                    //
// ---------------------------------------------------------------- //
function getLocationList() {
  const steps = [
    S.comment("Description: Returns the location list and startup state to the web viewer."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-startup.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("PARAMS"),
    S.setVar("$callbackName", `JSONGetElement ( Get ( ScriptParameter ) ; "callbackName" )`),
    S.setVar("$promiseID", `JSONGetElement ( Get ( ScriptParameter ) ; "promiseID" )`),
    S.setVar("$webviewer", `"${WEBVIEWER}"`),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.comment(""),
    S.banner("GATHER"),
    S.comment("Locations::asJSONList already produces the list shape the widget wants."),
    S.comment(""),
    S.comment("No JSONFormatElements here. It only adds indentation, which the widget"),
    S.comment("throws away on parse -- but it roughly doubles the payload, and this"),
    S.comment("route is ~148KB of JSON before formatting. Perform JavaScript in Web"),
    S.comment("Viewer has to carry the whole thing as one parameter."),
    S.setVar(
      "$locations",
      `"[" & ExecuteSQL ( "select \\"asJSONList\\" from \\"Locations\\"" ; "" ; "," ) & "]"`
    ),
    S.comment(""),
    S.comment("If the SQL failed, ExecuteSQL yields \"?\" and the array is malformed."),
    S.comment("Say so rather than sending the web viewer something it cannot parse."),
    S.ifStep(`JSONGetElement ( $locations ; "[0]__ID" ) = "?" and $locations ≠ "[]"`),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "error" ; "Could not read the location list from this device's tables." ; JSONString ] )`
    ),
    S.performJS("$webviewer", "$callbackName", ["$promiseID", "$result"]),
    S.exitScript("$result"),
    S.endIf(),
    S.setVar(
      "$locationCount",
      `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"Locations\\"" ; "" ; "" ) ) )`
    ),
    S.comment(""),
    S.comment("f_pendingSync may not exist yet on an older copy of the file, in which"),
    S.comment("case ExecuteSQL returns \"?\" -- GetAsNumber turns that into nothing and"),
    S.comment("Max pins it at 0, so a missing field reads as \"nothing pending\"."),
    S.comment("Locations count too: UploadChanges sends both, and SaveEquipmentList"),
    S.comment("returns this same sum, so the badge doesn't jump between the two."),
    S.setVar(
      "$pendingCount",
      `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"CUSTOMER_EQUIPMENT\\" where \\"f_pendingSync\\" = 1" ; "" ; "" ) ) ) + Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select count(*) from \\"Locations\\" where \\"f_pendingSync\\" = 1" ; "" ; "" ) ) )`
    ),
    S.setVar(
      "$customers",
      `Let ( j = ExecuteSQL ( "select \\"CustomersJSON\\" from \\"Sync_Settings\\"" ; "" ; "" ) ; If ( IsEmpty ( j ) or j = "?" ; "[]" ; j ) )`
    ),
    S.setVar(
      "$lastSync",
      `Max ( 0 ; GetAsNumber ( ExecuteSQL ( "select \\"LastSyncUTC\\" from \\"Sync_Settings\\"" ; "" ; "" ) ) )`
    ),
    S.comment(""),
    S.banner("RETURN TO THE WEB VIEWER"),
    S.setVar(
      "$result",
      `JSONSetElement ( "{}" ; [ "locations" ; $locations ; JSONArray ] ; [ "locationCount" ; $locationCount ; JSONNumber ] ; [ "pendingCount" ; $pendingCount ; JSONNumber ] ; [ "lastSyncUTC" ; $lastSync ; JSONNumber ] ; [ "needsDownload" ; If ( $locationCount = 0 ; True ; False ) ; JSONBoolean ] ; [ "customers" ; $customers ; JSONArray ] )`
    ),
    S.performJS("$webviewer", "$callbackName", ["$promiseID", "$result"]),
    S.exitScript("$result"),
  ];
  return S.wrap(steps, { scriptName: "GetLocationList" });
}

// ---------------------------------------------------------------- //
// Startup                                                            //
// ---------------------------------------------------------------- //
function startup() {
  const steps = [
    S.comment("Description: Runs on file open. Loads the field app into the web viewer."),
    S.comment("Set this as the OnFirstWindowOpen trigger in File > File Options >"),
    S.comment("Script Triggers -- that setting cannot be pasted in."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-startup.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("INITIALIZE"),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.setVar("$webViewerName", `"${WEBVIEWER}"`),
    S.setVar("$appName", `"${APP_NAME}"`),
    S.comment(""),
    S.banner("SIGNED IN AS GUEST?"),
    S.comment("Every copy opens as [Guest] (File Options -> Log in using Guest account)."),
    S.comment("Before First Setup that is how the Download button's URL gets in; after it,"),
    S.comment("the tech signs in with their own account. FileMaker would not deactivate"),
    S.comment("[Guest] from a script (Enable Account: error 212, local or hosted), so the"),
    S.comment("switch happens here instead. Startup runs with full access so it can read"),
    S.comment("Sync_Settings while still signed in as Guest."),
    S.ifStep(`Get ( AccountName ) = "[Guest]"`),
    S.setVar("$setUp", `GetAsNumber ( ExecuteSQL ( "select \\"Initialized\\" from \\"Sync_Settings\\"" ; "" ; "" ) ) = 1`),
    S.ifStep("not $setUp"),
    S.comment("Not set up: exit quietly. On an install, the Download button's URL opens the"),
    S.comment("copy and First Setup runs straight after this trigger -- a dialog here would"),
    S.comment("tell the tech to do what they are already doing. A script cannot see that a"),
    S.comment("URL script is queued, so no message either way."),
    S.exitScript(`""`),
    S.endIf(),
    S.comment("FileMaker's own sign-in dialog; FileMaker Go can keep the password in the keychain."),
    S.setVar("$try", "0"),
    S.loop(),
    S.setVar("$try", "$try + 1"),
    S.reLogin(),
    S.exitLoopIf(`Get ( AccountName ) ≠ "[Guest]" or $try ≥ 3`),
    S.endLoop(),
    S.ifStep(`Get ( AccountName ) = "[Guest]"`),
    S.showCustomDialog(
      `"Sign in needed"`,
      `"Sign in with your own account to use the field app. Close the file and open it again to try again."`
    ),
    S.exitScript(`""`),
    S.endIf(),
    S.endIf(),
    S.comment(""),
    S.banner("RESOLVE THE WIDGET SOURCE"),
    S.comment("The widget comes from the HTML table, the house home for web viewer"),
    S.comment("code: npm run deploy-to-fm runs UploadToHTML, which writes the inlined"),
    S.comment("build into the record whose Name matches widget.config.js."),
    S.comment(""),
    S.comment("There is deliberately no $$Dev / localhost branch here. Loading the"),
    S.comment("parcel dev server into the web viewer is a developer convenience that"),
    S.comment("has no business running on a field device; develop in a browser and"),
    S.comment("deploy to test the real thing."),
    S.setVar(
      "$stored",
      `ExecuteSQL ( "select \\"HTML\\" from \\"HTML\\" where \\"Name\\" = ?" ; "" ; "" ; $appName )`
    ),
    S.ifStep(`IsEmpty ( $stored )`),
    S.comment("Nothing deployed under this app name. Say so rather than loading an"),
    S.comment("empty data: URL and leaving the tech at a blank screen."),
    S.showCustomDialog(
      `"Field app not installed"`,
      `"No deployed copy of the field app was found in this file (HTML record \\"" & $appName & "\\"). Deploy it before using this device offline."`
    ),
    S.exitScript(
      `JSONSetElement ( "{}" ; [ "error" ; "no deployed widget" ; JSONString ] )`
    ),
    S.endIf(),
    S.comment(""),
    S.comment("FileMaker Pro: base64 data URL. Hand-escaping the raw HTML does not survive"),
    S.comment("the round trip: encoding % corrupts the modulo operator in the bundle and the"),
    S.comment("nested SVG data URI in the CSS, and a raw # cuts the document off."),
    S.comment(""),
    S.comment("FileMaker Go: a file in the temp folder. Go renders no base64 data URL at"),
    S.comment("all, and does not decode %-escapes in a plain one (# as %23 reached the"),
    S.comment("page literally and broke every selector) -- zTest - Web Viewer, 2026-10-15,"),
    S.comment("Go 26.0.3. Written fresh on every open; the temp folder is per session."),
    S.ifStep("Get ( SystemPlatform ) = 3"),
    S.setFieldByName(`"Sync_Settings::zg_RouteFile"`, `TextEncode ( $stored ; "utf-8" ; 1 )`),
    S.setVar("$widgetPath", `Get ( TemporaryPath ) & "widget.html"`),
    S.exportFieldContents({ table: "Sync_Settings", id: 36, name: "zg_RouteFile" }, "$widgetPath"),
    S.setVar("$widgetError", "Get ( LastError )"),
    S.setFieldByName(`"Sync_Settings::zg_RouteFile"`, `""`),
    S.ifStep("$widgetError ≠ 0"),
    S.showCustomDialog(`"Field app could not start"`, `"Could not prepare the field app on this iPad (error " & $widgetError & "). Close the file and open it again."`),
    S.exitScript(`JSONSetElement ( "{}" ; [ "error" ; "widget file " & $widgetError ; JSONString ] )`),
    S.endIf(),
    S.setVar("$html", `"file://" & $widgetPath`),
    S.elseStep(),
    S.setVar("$html", `"data:text/html;base64," & Base64EncodeRFC ( 4648 ; $stored )`),
    S.endIf(),
    S.comment(""),
    S.banner("RENDER"),
    S.comment("Open on the field interface regardless of where the file was last left."),
    S.goToLayout(WIDGET_LAYOUT.id, WIDGET_LAYOUT.name),
    S.comment(""),
    S.comment("Blanking the URL first forces a reload even when it has not changed."),
    S.setWebViewer("$webViewerName", `""`),
    S.setWebViewer("$webViewerName", "$html"),
    S.comment(""),
    S.comment("No data is pushed here. The widget calls GetLocationList itself once it"),
    S.comment("is running, which is what reports whether a download is needed and how"),
    S.comment("many edits are waiting to upload -- so that state reaches the tech in"),
    S.comment("the interface rather than in a dialog they dismiss before reading."),
    S.exitScript(`""`),
  ];
  // Full access: see SIGNED IN AS GUEST above.
  return S.wrap(steps, { scriptName: "Startup" }).replace('runFullAccess="False"', 'runFullAccess="True"');
}

const OUT = [
  ["Startup.xml", startup()],
  ["GetLocationList.xml", getLocationList()],
];

const dir = path.join(__dirname, "..", "fmscripts");
fs.mkdirSync(dir, { recursive: true });
for (const [name, xml] of OUT) {
  fs.writeFileSync(path.join(dir, name), xml);
  console.log(`\x1b[32mWrote fmscripts/${name}\x1b[0m`);
}

// Clipboard, like the other generators: Startup by default, GetLocationList
// with  node ./scripts/generate-startup list
if (process.platform === "darwin") {
  const { spawn, exec } = require("child_process");
  const [name, xml] = process.argv[2] === "list" ? OUT[1] : OUT[0];
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log(`\x1b[32mCopied ${name} as a whole FileMaker script -- paste into the offline file's scripts list.\x1b[0m`);
      }
    );
  });
}
