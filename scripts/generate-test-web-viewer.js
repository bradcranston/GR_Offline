// -----------------------------------------------------------------------
// Generates "zTest - Web Viewer": which URLs will FileMaker Go's web viewer
// actually load on the Home layout?
// -----------------------------------------------------------------------
//   node ./scripts/generate-test-web-viewer
//
// zTest - Field App State showed, on a local copy in FileMaker Go signed in as
// a FieldTech account with the route imported and the widget present, that
// GetLayoutObjectAttribute ( "web" ; "source" ) stays 11 characters
// ("about:blank") even after Startup's Set Web Viewer with the base64 data URL.
// This tries four sources one at a time, reads the source back after each and
// asks what is on screen:
//   A  short plain data URL     data:text/html,<h1>...</h1>
//   B  short base64 data URL    data:text/html;base64,...
//   C  the widget, base64       exactly what Startup sets (~52,000 chars)
//   D  an https page            https://example.com
// Run it in the hosted offline sandbox copy from FileMaker Go (Admin is fine);
// no reinstall needed. Throwaway.
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

// Same builder Startup uses.
const setWV = (urlCalc) => S.setWebViewer(`"web"`, urlCalc);

// Run 1 (2026-10-15, FileMaker Go 26.0.3, hosted): A plain data URL showed;
// B short base64 data URL did NOT; C the widget as base64 (51,862 chars) did
// NOT; D https showed. GetLayoutObjectAttribute "source" said about:blank
// even for A, so on Go it cannot be trusted for data URLs -- judge by eye.
// Run 2 tries three ways to load the REAL widget without base64:
const WIDGET = `ExecuteSQL ( "select \\"HTML\\" from \\"HTML\\" where \\"Name\\" = ?" ; "" ; "" ; "GasketsRockField" )`;
const TESTS = [
  ["E", "widget, data URL, GetAsURLEncoded", `"data:text/html;charset=utf-8," & GetAsURLEncoded ( ${WIDGET} )`],
  ["F", "widget, plain data URL, only # escaped", `"data:text/html;charset=utf-8," & Substitute ( ${WIDGET} ; "#" ; "%23" )`],
  ["G", "widget, file in the temp folder", "$fileUrl"],
];

const steps = [
  S.comment("Which web viewer sources load in FileMaker Go. Safe to delete."),
  S.comment("Generated by scripts/generate-test-web-viewer.js."),
  S.setErrorCapture(true),
  S.goToLayout(19, "Home"),
  S.setVar("$report", `JSONSetElement ( "{}" ; [ "device" ; Get ( ApplicationVersion ) ; JSONString ] ; [ "hosted" ; Left ( Get ( FilePath ) ; 6 ) = "fmnet:" ; JSONBoolean ] )`),
  S.comment("For G: write the widget to the temp folder through the global container."),
  S.setFieldByName(`"Sync_Settings::zg_RouteFile"`, `TextEncode ( ${WIDGET} ; "utf-8" ; 1 )`),
  S.setVar("$tempPath", `Get ( TemporaryPath ) & "widget.html"`),
  S.exportFieldContents({ table: "Sync_Settings", id: 36, name: "zg_RouteFile" }, "$tempPath"),
  S.setVar("$tempError", "Get ( LastError )"),
  S.setFieldByName(`"Sync_Settings::zg_RouteFile"`, `""`),
  S.setVar("$fileUrl", `"file://" & $tempPath`),
  S.setVar("$report", `JSONSetElement ( $report ; [ "tempExportError" ; $tempError ; JSONNumber ] ; [ "fileUrl" ; $fileUrl ; JSONString ] )`),
  ...TESTS.flatMap(([k, label, url]) => [
    S.comment(""),
    S.banner(`TEST ${k}: ${label.toUpperCase()}`),
    S.setVar("$url", url),
    setWV(`""`),
    setWV("$url"),
    S.setVar("$setError", "Get ( LastError )"),
    S.pause(2),
    S.setVar("$source", `GetLayoutObjectAttribute ( "web" ; "source" )`),
    S.showCustomDialogButtons(
      `"Test ${k}: ${label}"`,
      `"URL length " & Length ( $url ) & ", web viewer now reports " & Length ( $source ) & " chars (" & Left ( $source ; 30 ) & ")." & ¶ & ¶ & "Look behind this box: does the field app (or any page) show in the web viewer?"`,
      ["App shows", "Still ? / blank"]
    ),
    S.setVar(
      "$report",
      `JSONSetElement ( $report ; "${k}" ; JSONSetElement ( "{}" ; [ "test" ; "${label}" ; JSONString ] ; [ "urlLength" ; Length ( $url ) ; JSONNumber ] ; [ "setError" ; $setError ; JSONNumber ] ; [ "sourceLength" ; Length ( $source ) ; JSONNumber ] ; [ "sourceStart" ; Left ( $source ; 30 ) ; JSONString ] ; [ "youSaw" ; If ( Get ( LastMessageChoice ) = 1 ; "app" ; "nothing" ) ; JSONString ] ) ; JSONObject )`
    ),
  ]),
  S.showCustomDialog(`"Web viewer test"`, "JSONFormatElements ( $report )"),
  S.exitScript("$report"),
];
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<fmxmlsnippet type="FMObjectList">\n<Script includeInMenu="True" SiriShortcutVisible="False" runFullAccess="True" id="0" name="zTest - Web Viewer">\n${steps.join("\n")}\n</Script>\n</fmxmlsnippet>`;
const outPath = path.join(__dirname, "..", "fmscripts", "TestWebViewer.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);
if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec("osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'", (error) => {
      if (error) return console.error(error);
      console.log("\x1b[32mCopied -- paste into the hosted offline SANDBOX copy.\x1b[0m");
    });
  });
}
