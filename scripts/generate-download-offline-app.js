// -----------------------------------------------------------------------
// Generates "Download Offline App" -- the live-file half of the install.
// -----------------------------------------------------------------------
//   node ./scripts/generate-download-offline-app
//
// Lives in GSR_Gaskets Rock(_Sandbox), the data file, which holds OfflineApp.
// The button users press belongs in the UI file, GasketsRock(_Sandbox): a
// button whose action is Perform Script [ "Download Offline App" from file
// GSR_Gaskets Rock ]. Both files are open on the iPad, so the script runs
// locally and Export Field Contents writes into FileMaker Go's Documents.
//
//   1. The account is the live session's Get ( AccountName ) -- already
//      authenticated. Accounts the offline master already has are refused.
//   2. The OfflineApp record is the one whose Name matches THIS file's
//      environment: GasketsRockOffline_Sandbox in a file whose name contains
//      "Sandbox", GasketsRockOffline otherwise. inSandbox in the installed copy
//      reads its file name, so the name decides which server it talks to.
//   3. Confirms first: an existing copy on the iPad is replaced, and edits it
//      has not uploaded would be lost.
//   4. Export Field Contents to Get ( DocumentsPath ) & Name & ".fmp12", then
//      Open URL fmp://~/<Name>.fmp12?script=First Setup&param=<account>.
//
// Proven by zProbe - Download Offline App (install probe runs 2-3, iPad).
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const SCRIPT = "Download Offline App";
const APP = { layout: { id: 342, name: "OfflineApp" }, to: "OfflineApp" }; // DDR 2026-10-15
const SETUP_SCRIPT = "First Setup";
const RESERVED = ["admin", "[guest]"];

function build() {
  const steps = [
    S.comment("Description: Installs the offline field app on this iPad for the signed-in user."),
    S.comment("Run from the Download offline app button in GasketsRock."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-download-offline-app.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.setErrorCapture(true),
    S.allowUserAbort(false),
    S.setVar("$account", "Get ( AccountName )"),
    S.ifStep(`not IsEmpty ( FilterValues ( Lower ( $account ) ; "${RESERVED.join("¶")}" ) )`),
    S.showCustomDialog(`"Use your own account"`, `"The field app is set up for the person signed in. Sign in to Gaskets Rock with your own account, not " & $account & ", and try again."`),
    S.exitScript(`""`),
    S.endIf(),
    S.comment(""),
    S.comment("Which copy: the one for this file's environment, so a sandbox copy can"),
    S.comment("never be installed from production or the other way round."),
    S.setVar("$name", `If ( PatternCount ( Get ( FileName ) ; "Sandbox" ) ; "GasketsRockOffline_Sandbox" ; "GasketsRockOffline" )`),
    S.goToLayout(APP.layout.id, APP.layout.name),
    S.enterFindMode(),
    S.setFieldByName(`"${APP.to}::Name"`, `"==" & $name`),
    S.performFindCurrent(),
    S.ifStep(`Get ( LastError ) ≠ 0 or IsEmpty ( ${APP.to}::File )`),
    S.showCustomDialog(`"Not available"`, `"The field app (" & $name & ") hasn't been uploaded yet. Ask the office."`),
    S.exitScript(`""`),
    S.endIf(),
    S.comment(""),
    S.showCustomDialogButtons(
      `"Download the field app"`,
      `"This installs the field app on this iPad for " & $account & " and downloads your route." & ¶ & ¶ & "If the field app is already on this iPad it will be replaced -- upload any changes you haven't sent first."`,
      ["Cancel", "Download"]
    ),
    S.ifStep("Get ( LastMessageChoice ) ≠ 2"),
    S.exitScript(`""`),
    S.endIf(),
    S.setVar("$path", `Get ( DocumentsPath ) & $name & ".fmp12"`),
    S.exportFieldContents({ table: APP.to, name: "File" }, "$path"),
    S.setVar("$exportError", "Get ( LastError )"),
    S.ifStep("$exportError ≠ 0"),
    S.showCustomDialog(
      `"Download failed"`,
      `"Could not save the field app to this iPad (error " & $exportError & "). If it is open, close it and try again."`
    ),
    S.exitScript(`""`),
    S.endIf(),
    S.openURL(
      `"fmp://~/" & $name & ".fmp12?script=" & GetAsURLEncoded ( "${SETUP_SCRIPT}" ) & "&param=" & GetAsURLEncoded ( $account )`
    ),
    S.exitScript(`""`),
  ];
  return S.wrap(steps, { scriptName: SCRIPT });
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "DownloadOfflineApp.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log("\x1b[32mCopied -- paste into the scripts list of GSR_Gaskets Rock_Sandbox.\x1b[0m");
      }
    );
  });
}
