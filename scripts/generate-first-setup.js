// -----------------------------------------------------------------------
// Generates "First Setup" -- turns a freshly downloaded copy into one tech's.
// -----------------------------------------------------------------------
//   node ./scripts/generate-first-setup
//
// Lives in the offline file. The live file's Download Offline App opens a new
// copy with  fmp://~/<Name>.fmp12?script=First Setup&param=<account>  -- the
// account of the person signed in to the live file. The copy signs in as
// [Guest] automatically (File Options) and this runs:
//
//   1. Refuses without an account, for a name the master already has
//      (Admin, [Guest] -- install probe run 2: Add Account 12, Re-Login 212),
//      and in a copy that is already set up.
//   2. Asks once for a password, into Sync_Settings::zg_SetupPassword, cleared
//      straight after. It never travels: not in the URL, not read from Users.
//   3. Add Account [ account ; password ; FieldTech ], marks the copy set up
//      (Sync_Settings::Initialized), Re-Login as the new account.
//   4. Import Route, offering Try Again on failure -- the account stays either
//      way, and Startup will ask for it at the next open.
//   5. Startup, so the widget loads with the route (it ran as Guest, before
//      there was any data).
//
// [Guest] stays active: FileMaker returned 212 for Enable Account on it.
// Startup switches a Guest sign-in to the tech's account instead.
//
// Runs with full access -- account steps require it. Proven on FileMaker Go by
// zProbe - First Setup (install probe run 3: Add Account 0, Re-Login 0).
// -----------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { spawn, exec } = require("child_process");
const S = require("./fmSteps");

const SCRIPT = "First Setup";
const PASSWORD_FIELD = { table: "Sync_Settings", id: 37, name: "zg_SetupPassword" };
const PRIVILEGE_SET = { name: "FieldTech" }; // must exist before pasting (ODATA_ACCOUNT.md)
const SETTINGS_LAYOUT = { id: 4, name: "Sync_Settings" };
const RESERVED = ["admin", "[guest]"];

const say = (title, message) => S.showCustomDialog(`"${title}"`, message);

function build() {
  const steps = [
    S.comment("Description: Creates this tech's account in a freshly downloaded copy, signs"),
    S.comment("in as it and downloads their route. Opened by the live file's Download button."),
    S.comment("#################### #"),
    S.comment("Generated by scripts/generate-first-setup.js -- edit that, not this."),
    S.comment("#################### #"),
    S.comment(""),
    S.banner("WHO, AND IS THIS COPY READY FOR IT?"),
    S.setErrorCapture(true),
    S.comment("Freeze: keeps the settings and import layouts off screen; dialogs still show."),
    S.freezeWindow(),
    S.allowUserAbort(false),
    S.comment("The URL passes plain text; a caller may also pass { \"account\": ... }."),
    S.setVar(
      "$account",
      `Let ( [ p = Get ( ScriptParameter ) ; j = JSONGetElement ( p ; "account" ) ] ; Trim ( If ( Left ( p ; 1 ) = "{" and Left ( j ; 1 ) ≠ "?" ; j ; p ) ) )`
    ),
    S.ifStep("IsEmpty ( $account )"),
    say("Open from Gaskets Rock", `"Set up the field app from the Download offline app button in Gaskets Rock."`),
    S.exitScript(`""`),
    S.endIf(),
    S.ifStep(`not IsEmpty ( FilterValues ( Lower ( $account ) ; "${RESERVED.join("¶")}" ) )`),
    say("Can't set up this account", `"The account " & $account & " can't be used in the field app. Sign in to Gaskets Rock with your own account and download again."`),
    S.exitScript(`""`),
    S.endIf(),
    S.ifStep(`GetAsNumber ( ExecuteSQL ( "select \\"Initialized\\" from \\"Sync_Settings\\"" ; "" ; "" ) ) = 1`),
    say("Already set up", `"This copy is already set up. Close it and open it again to sign in."`),
    S.exitScript(`""`),
    S.endIf(),
    S.comment(""),
    S.banner("PASSWORD, TYPED ONCE"),
    S.setVar("$pw", `""`),
    S.setVar("$try", "0"),
    S.loop(),
    S.setVar("$try", "$try + 1"),
    S.setFieldByName(`"${PASSWORD_FIELD.table}::${PASSWORD_FIELD.name}"`, `""`),
    S.showCustomDialogInput(
      `"Set up the field app"`,
      `"Account: " & $account & ¶ & ¶ & "Choose the password you will use to open the field app on this iPad." & If ( $try > 1 ; ¶ & ¶ & "Use at least 4 characters." ; "" )`,
      ["Continue", "Cancel"],
      [{ ...PASSWORD_FIELD, label: "Password", password: true }]
    ),
    S.setVar("$choice", "Get ( LastMessageChoice )"),
    S.setVar("$pw", `${PASSWORD_FIELD.table}::${PASSWORD_FIELD.name}`),
    S.setFieldByName(`"${PASSWORD_FIELD.table}::${PASSWORD_FIELD.name}"`, `""`),
    S.exitLoopIf(`$choice ≠ 1 or Length ( $pw ) ≥ 4`),
    S.endLoop(),
    S.ifStep(`$choice ≠ 1`),
    S.setVar("$pw", `""`),
    say("Setup cancelled", `"Nothing was changed. Download again from Gaskets Rock when you're ready."`),
    S.exitScript(`""`),
    S.endIf(),
    S.comment(""),
    S.banner("CREATE THE ACCOUNT, MARK THE COPY, SIGN IN"),
    S.addAccount("$account", "$pw", PRIVILEGE_SET),
    S.setVar("$addError", "Get ( LastError )"),
    S.ifStep("$addError ≠ 0"),
    S.setVar("$pw", `""`),
    say("Setup failed", `"Could not create the account " & $account & " (error " & $addError & "). Ask the office."`),
    S.exitScript(`JSONSetElement ( "{}" ; [ "error" ; "Add Account " & $addError ; JSONString ] )`),
    S.endIf(),
    S.comment("Marked now, before the route downloads: if the download fails, Startup still"),
    S.comment("asks for this account at the next open instead of saying \"not set up\"."),
    S.goToLayout(SETTINGS_LAYOUT.id, SETTINGS_LAYOUT.name),
    S.ifStep("Get ( FoundCount ) = 0"),
    S.newRecord(),
    S.endIf(),
    S.setFieldByName(`"Sync_Settings::Initialized"`, `"1"`),
    S.commit(),
    S.reLogin("$account", "$pw"),
    S.setVar("$reloginError", "Get ( LastError )"),
    S.setVar("$pw", `""`),
    S.ifStep(`$reloginError ≠ 0 or Get ( AccountName ) ≠ $account`),
    say("Sign-in failed", `"Your account was created but signing in failed (error " & $reloginError & "). Close the file and open it again, then sign in as " & $account & "."`),
    S.exitScript(`JSONSetElement ( "{}" ; [ "error" ; "Re-Login " & $reloginError ; JSONString ] )`),
    S.endIf(),
    S.comment(""),
    S.banner("DOWNLOAD THE ROUTE"),
    S.loop(),
    S.performScriptWithParam("Import Route", `JSONSetElement ( "{}" ; "account" ; $account ; JSONString )`),
    S.setVar("$route", "Get ( ScriptResult )"),
    S.setVar("$routeError", `Let ( e = JSONGetElement ( $route ; "error" ) ; If ( Left ( e ; 1 ) = "?" ; "" ; e ) )`),
    S.exitLoopIf("IsEmpty ( $routeError )"),
    S.showCustomDialogButtons(
      `"Route not downloaded"`,
      `$routeError & ¶ & ¶ & "Your account is set up. You can try again now, or later when you have a connection."`,
      ["Try Again", "Later"]
    ),
    S.exitLoopIf("Get ( LastMessageChoice ) ≠ 1"),
    S.endLoop(),
    S.comment(""),
    S.banner("SHOW THE APP"),
    S.comment("Startup ran as Guest, before there was any data; run it again as the tech."),
    S.performScript(0, "Startup"),
    S.exitScript(
      `JSONSetElement ( "{}" ; [ "account" ; $account ; JSONString ] ; [ "route" ; $route ; JSONObject ] )`
    ),
  ];
  return S.wrap(steps, { scriptName: SCRIPT }).replace('runFullAccess="False"', 'runFullAccess="True"');
}

const xml = build();
const outPath = path.join(__dirname, "..", "fmscripts", "FirstSetup.xml");
fs.writeFileSync(outPath, xml);
console.log(`\x1b[32mWrote ${path.relative(process.cwd(), outPath)}\x1b[0m`);

if (process.platform === "darwin") {
  const proc = spawn("pbcopy");
  proc.stdin.write(xml);
  proc.stdin.end();
  proc.on("close", () => {
    exec(
      "osascript -e 'set the clipboard to (do shell script \"pbpaste\" as «class XMSC»)'",
      (error) => {
        if (error) return console.error(error);
        console.log("\x1b[32mCopied as a whole FileMaker script -- paste into the offline file's scripts list.\x1b[0m");
      }
    );
  });
}
